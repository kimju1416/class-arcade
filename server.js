// ---------- 초성 퀴즈 ----------
function startChoRound(room, now) {
  const g = room.game;
  g.round++;
  // 1~4라운드: 자유 카테고리(음식·동물·사물장소)의 짧은 초성 → 사전 속 단어를 먼저 떠올리는 싸움
  // 5라운드: 영화·노래 제목 (마무리 보너스 라운드)
  const freeCats = Object.keys(CHO_INDEX).filter(c => CHO_FREE_CATS.has(c));
  const titleCats = Object.keys(CHO_INDEX).filter(c => !CHO_FREE_CATS.has(c));
  const useTitle = g.round >= WORD_ROUNDS && titleCats.length > 0;
  const pool = useTitle ? titleCats : (freeCats.length ? freeCats : Object.keys(CHO_INDEX));

  for (let tryN = 0; tryN < 120; tryN++) {
    const cat = pool[Math.floor(Math.random() * pool.length)];
    const patterns = [...CHO_INDEX[cat].keys()];
    const pattern = patterns[Math.floor(Math.random() * patterns.length)];
    if (g.usedPatterns.has(cat + ':' + pattern)) continue;
    const answers = CHO_INDEX[cat].get(pattern);
    // 자유 카테고리는 2~3글자 초성이라야 떠올릴 단어가 많다
    if (!useTitle && tryN < 90 && (pattern.length < 2 || pattern.length > 3)) continue;
    // 사전 대조 판정이라 정답이 여럿인 문제라야 여러 명이 점수를 딸 수 있다
    if (!useTitle && tryN < 70 && answers.length < 3) continue;
    // 제목 카테고리는 정답이 여러 개인 쪽이 눈치싸움이 된다
    if (useTitle && tryN < 60 && answers.length < 2) continue;
    g.usedPatterns.add(cat + ':' + pattern);
    g.category = cat; g.pattern = pattern;
    g.answers = new Set(answers);
    break;
  }
  // 안 쓴 패턴을 못 찾은 경우(사전이 작아지면 생길 수 있음) 아무 문제나 하나 강제 배정
  if (!g.pattern || !g.answers) {
    const cat = pool[0] || Object.keys(CHO_INDEX)[0];
    const pattern = [...CHO_INDEX[cat].keys()][0];
    g.category = cat; g.pattern = pattern;
    g.answers = new Set(CHO_INDEX[cat].get(pattern));
  }
  g.wordPhase = 'show';
  g.roundEndAt = now + CHO_ROUND_MS;
  g.correctOrder = []; g.claimed = [];
  for (const p of room.players.values()) p.wordDone = false;
}

function choTick(room, now) {
  const g = room.game;
  const actives = [...room.players.values()].filter(p => p.alive && p.connected);
  if (g.wordPhase === 'show') {
    const allDone = actives.length > 0 && actives.every(p => p.wordDone);
    // 사전에 있는 정답이 다 나왔으면 더 기다릴 필요 없음
    const exhausted = g.answers && g.claimed.length >= g.answers.size;
    if (now >= g.roundEndAt || allDone || exhausted) {
      g.wordPhase = 'break';
      g.breakEndAt = now + WORD_BREAK_MS;
    }
  } else if (g.wordPhase === 'break') {
    if (now >= g.breakEndAt) {
      if (g.round >= WORD_ROUNDS) { endWord(room); return; }
      startChoRound(room, now);
    }
  }
  sendState(room, now);
}

// ---------- 갤러그 ----------
function galaSpawnWave(g, now) {
  g.wave++;
  const w = g.wave;
  const cols = Math.min(10, 5 + w), rows = Math.min(4, 1 + Math.ceil(w / 2));
  const gapX = (g.arenaW - 140) / (cols - 1);
  for (let r = 0; r < rows; r++)
    for (let c = 0; c < cols; c++)
      g.enemies.push({
        id: g.nextEnemyId++,
        x: 70 + c * gapX, y: 80 + r * 64,
        mode: 'form',                        // form=편대 행진, dive=급강하
        elite: r === 0 && (c + w) % 3 === 0, // 맨 앞줄 일부는 정예(3점)
        vx: 0, vy: 0, fireAt: now + 3000 + Math.random() * 4000,
      });
  g.formDir = 1;
  g.formSpeed = 46 + w * 9;                  // 웨이브마다 편대가 빨라진다
  g.fireGap = Math.max(450, 2400 - w * 200); // 발사도 잦아진다
  g.diveGap = Math.max(3000, 10000 - w * 700);
  g.ebSpeed = Math.min(320, 140 + w * 18);
}

function galaTick(room, now, dt) {
  const g = room.game;
  const alivePs = [...room.players.values()].filter(p => p.alive);

  // 웨이브 시작/클리어
  if (!g.enemies.length) {
    if (!g.nextWaveAt) g.nextWaveAt = now + 1600;
    if (now >= g.nextWaveAt) { galaSpawnWave(g, now); g.nextWaveAt = 0; }
  }

  // 함선 이동 (아래쪽 구역 안에서만)
  for (const p of room.players.values()) {
    if (!p.alive) continue;
    p.x = Math.max(GALA_SHIP_R, Math.min(g.arenaW - GALA_SHIP_R, p.x + p.dirX * SPEED * dt));
    p.y = Math.max(g.arenaH * 0.55, Math.min(g.arenaH - 30, p.y + p.dirY * SPEED * dt));
  }

  // 편대 행진 (좌우 왕복 + 벽에서 한 칸 내려옴)
  let hitWall = false;
  for (const e of g.enemies) {
    if (e.mode !== 'form') continue;
    e.x += g.formDir * g.formSpeed * dt;
    if (e.x < 50 || e.x > g.arenaW - 50) hitWall = true;
  }
  if (hitWall) {
    g.formDir *= -1;
    for (const e of g.enemies) if (e.mode === 'form') { e.y += 20; e.x += g.formDir * 4; }
  }

  // 급강하: 주기적으로 한 마리가 대열을 이탈해 함선을 향해 돌진
  if (now >= g.nextDiveAt && g.enemies.length && alivePs.length) {
    const formers = g.enemies.filter(e => e.mode === 'form');
    if (formers.length) {
      const e = formers[Math.floor(Math.random() * formers.length)];
      const target = alivePs[Math.floor(Math.random() * alivePs.length)];
      const ang = Math.atan2(target.y - e.y, target.x - e.x);
      const sp = 200 + g.wave * 22;
      e.mode = 'dive'; e.vx = Math.cos(ang) * sp; e.vy = Math.sin(ang) * sp;
      e.fireAt = now + 300;
    }
    g.nextDiveAt = now + g.diveGap;
  }
  for (const e of g.enemies) {
    if (e.mode !== 'dive') continue;
    e.x += e.vx * dt; e.y += e.vy * dt;
    e.vx += Math.sin(now / 130 + e.id) * 60 * dt;   // 살짝 흔들리며 내려온다
  }
  g.enemies = g.enemies.filter(e => e.mode !== 'dive' || e.y < g.arenaH + 40);

  // 적 발사 (조준탄)
  for (const e of g.enemies) {
    if (now < e.fireAt || !alivePs.length) continue;
    e.fireAt = now + g.fireGap * (0.7 + Math.random() * 0.8) * (e.mode === 'dive' ? 0.5 : 1);
    const target = alivePs[Math.floor(Math.random() * alivePs.length)];
    const ang = Math.atan2(target.y - e.y, target.x - e.x) + (Math.random() - 0.5) * 0.25;
    g.eb.push({ x: e.x, y: e.y, vx: Math.cos(ang) * g.ebSpeed, vy: Math.sin(ang) * g.ebSpeed });
  }

  // 총알 이동
  for (const bl of g.pb) bl.y -= GALA_PB_SPEED * dt;
  for (const bl of g.eb) { bl.x += bl.vx * dt; bl.y += bl.vy * dt; }
  g.pb = g.pb.filter(bl => bl.y > -20);
  g.eb = g.eb.filter(bl => bl.x > -20 && bl.x < g.arenaW + 20 && bl.y > -20 && bl.y < g.arenaH + 20);
  if (g.eb.length > 200) g.eb.splice(0, g.eb.length - 200);   // 고웨이브 탄 폭주 상한

  // 명중 판정: 내 총알 → 적
  g.kills = [];
  for (const bl of g.pb) {
    for (const e of g.enemies) {
      const dx = bl.x - e.x, dy = bl.y - e.y;
      if (dx * dx + dy * dy <= GALA_ENEMY_R * GALA_ENEMY_R) {
        bl.hit = true; e.dead = true;
        g.kills.push([Math.round(e.x), Math.round(e.y)]);
        const owner = room.players.get(bl.owner);
        if (owner) owner.score += e.elite ? 3 : 1;
        break;
      }
    }
  }
  g.pb = g.pb.filter(bl => !bl.hit);
  g.enemies = g.enemies.filter(e => !e.dead);

  // 피격 판정: 적탄·급강하 몸통 → 함선 (죽으면 끝)
  for (const p of alivePs) {
    for (const bl of g.eb) {
      const dx = bl.x - p.x, dy = bl.y - p.y;
      if (dx * dx + dy * dy <= (GALA_SHIP_R + 6) * (GALA_SHIP_R + 6)) { p.alive = false; p.deadAt = now; bl.hitP = true; break; }
    }
    if (!p.alive) continue;
    for (const e of g.enemies) {
      if (e.mode !== 'dive') continue;
      const dx = e.x - p.x, dy = e.y - p.y;
      if (dx * dx + dy * dy <= (GALA_SHIP_R + GALA_ENEMY_R * 0.8) * (GALA_SHIP_R + GALA_ENEMY_R * 0.8)) { p.alive = false; p.deadAt = now; break; }
    }
  }
  g.eb = g.eb.filter(bl => !bl.hitP);

  const stillAlive = [...room.players.values()].filter(p => p.alive);
  if (!stillAlive.length || now >= room.phaseEndAt) { endGala(room, now); return; }
  sendState(room, now);
}

function endGala(room, now) {
  const parts = [...room.players.values()].filter(p => !p.waiting);
  const sorted = parts.sort((a, b) => {
    if (b.score !== a.score) return b.score - a.score;
    const ad = a.alive ? Infinity : a.deadAt, bd = b.alive ? Infinity : b.deadAt;
    return bd - ad;
  });
  finishGame(room, sorted,
    p => p.score + '격추' + (p.alive ? ' · 생존' : ''),
    p => p.score + '|' + (p.alive ? 'a' : p.deadAt));
}

// ---------- 탄막 서바이벌 ----------
function dodgeTick(room, now, dt) {
  const g = room.game;
  const el = now - g.startedAt;              // 경과 시간 = 난이도
  const W = g.arenaW, H = g.arenaH;
  movePlayers(room, dt);
  const alivePs = [...room.players.values()].filter(p => p.alive);

  const bSpeed = Math.min(300, 105 + el / 220);  // 탄속: 105 → 300

  // 패턴 1: 가장자리 링 폭발 (점점 잦고 촘촘하게)
  if (now >= g.nextRingAt) {
    const side = Math.floor(Math.random() * 4);
    const px = side === 0 ? 0 : side === 1 ? W : Math.random() * W;
    const py = side < 2 ? Math.random() * H : (side === 2 ? 0 : H);
    const cnt = Math.min(24, 7 + Math.floor(el / 5000));
    for (let i = 0; i < cnt; i++) {
      const ang = (i / cnt) * Math.PI * 2;
      g.bullets.push({ x: px, y: py, vx: Math.cos(ang) * bSpeed, vy: Math.sin(ang) * bSpeed });
    }
    g.nextRingAt = now + Math.max(650, 2600 - el / 35);
  }
  // 패턴 2: 조준탄 3연발
  if (now >= g.nextAimAt && alivePs.length) {
    const t = alivePs[Math.floor(Math.random() * alivePs.length)];
    const srcs = [[0, Math.random() * H], [W, Math.random() * H], [Math.random() * W, 0], [Math.random() * W, H]];
    const src = srcs[Math.floor(Math.random() * 4)];
    const ang = Math.atan2(t.y - src[1], t.x - src[0]);
    for (let k = -1; k <= 1; k++) {
      const a2 = ang + k * 0.09;
      g.bullets.push({ x: src[0], y: src[1], vx: Math.cos(a2) * bSpeed * 1.25, vy: Math.sin(a2) * bSpeed * 1.25 });
    }
    g.nextAimAt = now + Math.max(450, 1800 - el / 50);
  }
  // 패턴 3: 15초부터 중앙 회오리
  if (el > 15000 && now >= g.nextSpiralAt) {
    g.spiralAngle += 0.55;
    for (const off of [0, Math.PI]) {
      const a2 = g.spiralAngle + off;
      g.bullets.push({ x: W / 2, y: H / 2, vx: Math.cos(a2) * bSpeed * 0.9, vy: Math.sin(a2) * bSpeed * 0.9 });
    }
    g.nextSpiralAt = now + Math.max(70, 160 - el / 1000);
  }

  // 탄 이동·정리
  for (const bl of g.bullets) { bl.x += bl.vx * dt; bl.y += bl.vy * dt; }
  g.bullets = g.bullets.filter(bl => bl.x > -25 && bl.x < W + 25 && bl.y > -25 && bl.y < H + 25);
  if (g.bullets.length > DODGE_MAX_BULLETS) g.bullets.splice(0, g.bullets.length - DODGE_MAX_BULLETS);

  // 피격 = 즉사 (죽으면 끝)
  for (const p of alivePs) {
    for (const bl of g.bullets) {
      const dx = bl.x - p.x, dy = bl.y - p.y;
      if (dx * dx + dy * dy <= (DODGE_BULLET_R + 12) * (DODGE_BULLET_R + 12)) { p.alive = false; p.deadAt = now; break; }
    }
  }

  const alive = [...room.players.values()].filter(p => p.alive);
  // 폭탄 피하기(최후 1인 종료)와 달리 혼자 남아도 계속 — 전멸하거나 시간이 다해야 끝난다
  if (now >= room.phaseEndAt || !alive.length) {
    endBomb(room, now);   // 순위 규칙이 폭탄 피하기와 같다 (생존자 → 늦게 죽은 순)
    return;
  }
  sendState(room, now);
}

// ---------- 스모 밀치기 ----------
function sumoTick(room, now, dt) {
  const g = room.game;
  const cx = g.arenaW / 2, cy = g.arenaH / 2;
  const el = now - g.startedAt;
  // 첫 15초는 링 유지, 이후 서서히 줄어든다 (대치 상태 방지)
  const shrinkT = Math.min(1, Math.max(0, el - 15000) / (SUMO_ROUND_MS - 20000));
  g.ringR = g.ringR0 * (1 - 0.55 * shrinkT);

  const alivePs = [...room.players.values()].filter(p => p.alive);
  for (const p of alivePs) {
    const dashing = now < (p.dashUntil || 0);
    const dx = dashing ? p.dashDx : p.dirX, dy = dashing ? p.dashDy : p.dirY;
    const acc = dashing ? SUMO_DASH_ACC : SUMO_ACC;
    p.vx = (p.vx || 0) + dx * acc * dt;
    p.vy = (p.vy || 0) + dy * acc * dt;
    const fr = Math.max(0, 1 - SUMO_FRICTION * dt);
    p.vx *= fr; p.vy *= fr;
    const v = Math.hypot(p.vx, p.vy), vmax = dashing ? SUMO_MAXV * 2.4 : SUMO_MAXV;
    if (v > vmax) { p.vx = p.vx / v * vmax; p.vy = p.vy / v * vmax; }
    p.x = Math.max(0, Math.min(g.arenaW, p.x + p.vx * dt));
    p.y = Math.max(0, Math.min(g.arenaH, p.y + p.vy * dt));
  }
  // 몸싸움: 겹치면 밀어내고, 부딪힌 속도만큼 서로 튕긴다 (대시 중이면 더 세게)
  for (let i = 0; i < alivePs.length; i++) {
    for (let j = i + 1; j < alivePs.length; j++) {
      const a = alivePs[i], b = alivePs[j];
      const dx = b.x - a.x, dy = b.y - a.y;
      const d2 = dx * dx + dy * dy, min = PLAYER_R * 2;
      if (d2 > 0.01 && d2 < min * min) {
        const d = Math.sqrt(d2), nx = dx / d, ny = dy / d, push = (min - d) / 2;
        a.x -= nx * push; a.y -= ny * push;
        b.x += nx * push; b.y += ny * push;
        const rel = (a.vx - b.vx) * nx + (a.vy - b.vy) * ny;   // 서로 다가가는 속도
        if (rel > 0) {
          const aD = now < (a.dashUntil || 0), bD = now < (b.dashUntil || 0);
          const k = rel * ((aD || bD) ? SUMO_KNOCK : 0.85);
          a.vx -= nx * k * (bD ? 1.35 : 1); a.vy -= ny * k * (bD ? 1.35 : 1);
          b.vx += nx * k * (aD ? 1.35 : 1); b.vy += ny * k * (aD ? 1.35 : 1);
          a.bumpAt = now; b.bumpAt = now;
        }
      }
    }
  }
  // 링 밖으로 나가면 장외
  for (const p of alivePs) {
    if (Math.hypot(p.x - cx, p.y - cy) > g.ringR + PLAYER_R * 0.35) { p.alive = false; p.deadAt = now; }
  }
  const alive = [...room.players.values()].filter(p => p.alive);
  if (now >= room.phaseEndAt || (g.startingCount >= 2 && alive.length <= 1) || !alive.length) {
    endBomb(room, now);   // 생존자 → 늦게 떨어진 순
    return;
  }
  sendState(room, now);
}

// ---------- 의자 뺏기 ----------
function chairTick(room, now, dt) {
  const g = room.game;
  // 의자에 앉은 사람은 그 자리에 고정
  movePlayers(room, dt, p => p.satChair != null ? 0 : SPEED);

  if (g.cphase === 'music') {
    if (now >= g.musicEndAt) {
      // 음악 정지 — 의자 소환! (인원의 약 2/3, 최종 2인전은 1개)
      const alive = [...room.players.values()].filter(p => p.alive);
      const count = alive.length <= 2 ? 1 : Math.max(1, Math.ceil(alive.length * 0.66));
      g.chairs = [];
      for (let i = 0; i < count; i++) {
        let x = 0, y = 0;
        for (let t2 = 0; t2 < 50; t2++) {
          x = 70 + Math.random() * (g.arenaW - 140);
          y = 70 + Math.random() * (g.arenaH - 140);
          if (g.chairs.every(c => Math.hypot(c.x - x, c.y - y) > CHAIR_R * 3.4)) break;
        }
        g.chairs.push({ x, y, owner: null });
      }
      g.cphase = 'grab'; g.grabEndAt = now + CHAIR_GRAB_MS;
    }
  } else if (g.cphase === 'grab') {
    const alive = [...room.players.values()].filter(p => p.alive);
    for (const p of alive) {
      if (p.satChair != null) continue;
      for (let ci = 0; ci < g.chairs.length; ci++) {
        const c = g.chairs[ci];
        if (c.owner != null) continue;
        if (Math.hypot(p.x - c.x, p.y - c.y) < CHAIR_R + PLAYER_R * 0.7) {
          c.owner = p.id; p.satChair = ci;
          p.x = c.x; p.y = c.y; p.dirX = 0; p.dirY = 0;
          break;
        }
      }
    }
    const allTaken = g.chairs.length > 0 && g.chairs.every(c => c.owner != null);
    if (allTaken || now >= g.grabEndAt) {
      for (const p of alive) if (p.satChair == null) { p.alive = false; p.deadAt = now; p.outRound = g.cRound; }
      const left = [...room.players.values()].filter(p => p.alive);
      if (left.length <= 1) { endChair(room); return; }
      g.cRound++;
      for (const p of left) p.satChair = null;
      g.chairs = [];
      g.cphase = 'music';
      g.musicEndAt = now + CHAIR_MUSIC_MIN + Math.random() * CHAIR_MUSIC_RAND;
    }
  }
  if (now >= room.phaseEndAt) { endChair(room); return; }
  sendState(room, now);
}

function endChair(room) {
  const parts = [...room.players.values()].filter(p => !p.waiting);
  const sorted = parts.sort((a, b) => {
    if (a.alive !== b.alive) return a.alive ? -1 : 1;
    return (b.deadAt || 0) - (a.deadAt || 0);
  });
  finishGame(room, sorted,
    p => p.alive ? '👑 끝까지 생존' : `${p.outRound}라운드 탈락`,
    p => p.alive ? 'alive' : String(p.deadAt));
}

// ---------- 사다리 복불복 ----------
function startSadariRound(room, now) {
  const g = room.game;
  g.round++;
  const L = SADARI_LANES, rows = 13;
  // 가로줄: 같은 행에서 이웃한 두 줄이 연달아 붙지 않게 (표준 사다리 규칙)
  g.rungs = [];
  for (let r = 0; r < rows; r++) {
    let prev = -2;
    for (let l = 0; l < L - 1; l++) {
      if (l - prev >= 2 && Math.random() < 0.34) { g.rungs.push([r, l]); prev = l; }
    }
  }
  g.prizes = [...SADARI_PRIZES].sort(() => Math.random() - 0.5);
  // 각 출발 칸이 어느 도착 칸으로 가는지 미리 계산
  g.map = [];
  for (let s = 0; s < L; s++) {
    let lane = s;
    for (let r = 0; r < rows; r++) {
      if (g.rungs.some(([rr, ll]) => rr === r && ll === lane)) lane++;
      else if (g.rungs.some(([rr, ll]) => rr === r && ll === lane - 1)) lane--;
    }
    g.map.push(lane);
  }
  g.sPhase = 'pick';
  g.pickEndAt = now + SADARI_PICK_MS;
  g.applied = false;
  for (const p of room.players.values()) p.pick = -1;
}

function sadariTick(room, now) {
  const g = room.game;
  const alive = [...room.players.values()].filter(p => p.alive && p.connected);
  if (g.sPhase === 'pick') {
    const allPicked = alive.length > 0 && alive.every(p => p.pick >= 0);
    if (now >= g.pickEndAt || allPicked) {
      // 못 고른 사람은 랜덤 칸 (복불복이니 억울할 것 없음)
      for (const p of room.players.values())
        if (p.alive && p.pick < 0) p.pick = Math.floor(Math.random() * SADARI_LANES);
      g.sPhase = 'reveal';
      g.revealAt = now; g.revealEndAt = now + SADARI_REVEAL_MS;
    }
  } else if (g.sPhase === 'reveal') {
    // 공이 바닥에 닿는 순간 점수 반영 (효과음 타이밍과 맞춤)
    if (!g.applied && now >= g.revealAt + SADARI_TRACE_MS) {
      g.applied = true;
      for (const p of room.players.values()) {
        if (p.waiting || p.pick < 0) continue;
        p.score += g.prizes[g.map[p.pick]];
      }
    }
    if (now >= g.revealEndAt) {
      if (g.round >= SADARI_ROUNDS) { endWord(room); return; }   // 점수 순위
      startSadariRound(room, now);
    }
  }
  sendState(room, now);
}

// ---------- 해적왕 통아저씨 ----------
function startPirateRound(room, now) {
  const g = room.game;
  g.round++;
  // 매 라운드 통을 리셋하고 위험 칸을 늘린다 (1라운드 4칸 → +1씩)
  const T = Math.min(10, 3 + g.round);
  const slots = [...Array(PIRATE_SLOTS).keys()].sort(() => Math.random() - 0.5);
  g.triggers = new Set(slots.slice(0, T));
  g.victims = [];
  g.pPhase = 'pick';
  g.pickEndAt = now + PIRATE_PICK_MS;
  g.applied = false;
  for (const p of room.players.values()) p.picks = [];
}

function pirateTick(room, now) {
  const g = room.game;
  const alive = [...room.players.values()].filter(p => p.alive && p.connected);
  if (g.pPhase === 'pick') {
    const allPicked = alive.length > 0 && alive.every(p => p.picks.length >= g.knives);
    if (now >= g.pickEndAt || allPicked) {
      // 시간 안에 다 못 꽂은 칼은 랜덤 칸에 (복불복이니 억울할 것 없음)
      for (const p of room.players.values()) {
        if (!p.alive) continue;
        let guard = 0;
        while (p.picks.length < g.knives && guard++ < 200) {
          const s = Math.floor(Math.random() * PIRATE_SLOTS);
          if (!p.picks.includes(s)) p.picks.push(s);
        }
      }
      g.victims = [];
      for (const p of room.players.values())
        if (p.alive && p.picks.some(s => g.triggers.has(s))) g.victims.push(p.id);
      g.pPhase = 'reveal';
      g.revealAt = now; g.revealEndAt = now + PIRATE_REVEAL_MS;
    }
  } else if (g.pPhase === 'reveal') {
    // 해적이 튀어나오는 순간 탈락 처리
    if (!g.applied && now >= g.revealAt + 1600) {
      g.applied = true;
      for (const id of g.victims) {
        const p = room.players.get(id);
        if (p && p.alive) { p.alive = false; p.deadAt = now; p.outRound = g.round; }
      }
    }
    if (now >= g.revealEndAt) {
      const left = [...room.players.values()].filter(p => p.alive);
      const goal = Math.max(1, Math.ceil(g.startingCount * 0.12));   // 마지막 소수 생존자가 우승
      if (left.length <= goal || g.round >= PIRATE_MAX_ROUNDS) { endPirate(room); return; }
      startPirateRound(room, now);
    }
  }
  sendState(room, now);
}

// ---------- OX 서바이벌 ----------
function startOxQ(room, now) {
  const g = room.game;
  g.oxPhase = 'show';
  g.oxEndAt = now + OX_Q_MS;
  g.oxRevived = false;
}

function oxTick(room, now, dt) {
  const g = room.game;
  movePlayers(room, dt);
  if (g.oxPhase === 'show') {
    if (now >= g.oxEndAt) {
      const [, answer] = g.oxQs[g.oxIdx];
      const alive = [...room.players.values()].filter(p => p.alive);
      // 정답 구역: O=왼쪽 절반, X=오른쪽 절반
      const wrong = alive.filter(p => (p.x < g.arenaW / 2 ? 0 : 1) !== answer);
      if (wrong.length >= alive.length) {
        g.oxRevived = true;   // 전원 오답이면 아무도 안 떨어뜨린다 (전원 부활!)
      } else {
        for (const p of wrong) { p.alive = false; p.deadAt = now; p.outRound = g.oxIdx + 1; }
      }
      g.oxPhase = 'reveal';
      g.revealEndAt = now + OX_REVEAL_MS;
    }
  } else if (g.oxPhase === 'reveal') {
    if (now >= g.revealEndAt) {
      const left = [...room.players.values()].filter(p => p.alive);
      if (left.length <= 1 || g.oxIdx + 1 >= g.oxQs.length) { endOx(room); return; }
      g.oxIdx++;
      startOxQ(room, now);
    }
  }
  sendState(room, now);
}

function endOx(room) {
  const parts = [...room.players.values()].filter(p => !p.waiting);
  const sorted = parts.sort((a, b) => {
    if (a.alive !== b.alive) return a.alive ? -1 : 1;
    return (b.outRound || 0) - (a.outRound || 0);
  });
  finishGame(room, sorted,
    p => p.alive ? '👑 끝까지 생존!' : `${p.outRound}번 문제에서 탈락`,
    p => p.alive ? 'alive' : String(p.outRound || 0));
}

