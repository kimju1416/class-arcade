// ---------- 레이싱 ----------
function raceTick(room, now, dt) {
  const g = room.game, t = g.track;
  const racers = [...room.players.values()].filter(p => p.alive);

  for (const p of racers) {
    if (p.finishedAt) continue;
    const spinning = now < (p.spinUntil || 0);
    // 기름을 밟으면 0.9초간 빙글 돌며 조종 불능
    if (spinning) {
      p.angle += 10 * dt;
    } else {
      // 조향: 조이스틱이 가리키는 방향으로 서서히 회전 (차라서 즉시 못 꺾는다)
      const len = Math.hypot(p.dirX, p.dirY);
      if (len > 0.25) {
        const target = Math.atan2(p.dirY, p.dirX);
        let d = target - p.angle;
        while (d > Math.PI) d -= Math.PI * 2;
        while (d < -Math.PI) d += Math.PI * 2;
        const maxTurn = RACE_TURN * dt;
        p.angle += Math.max(-maxTurn, Math.min(maxTurn, d));
      }
    }
    // 함정 판정
    let inWater = false;
    for (const hz of t.hazards) {
      const dx = p.x - hz.x, dy = p.y - hz.y;
      if (dx * dx + dy * dy > (hz.r + RACE_CAR_R * 0.5) * (hz.r + RACE_CAR_R * 0.5)) continue;
      if (hz.type === 'water') inWater = true;
      else if (hz.type === 'oil' && !spinning && now >= (p.spinImmuneUntil || 0)) {
        p.spinUntil = now + 900;
        p.spinImmuneUntil = now + 2400;  // 스핀 직후 같은 기름에 연속으로 안 걸리게
      }
    }
    const boosting = now < p.boostUntil;
    const off = p.trackDist > t.halfW;               // 잔디에 빠졌나
    let mult = off ? RACE_OFF_MULT : 1;
    if (inWater) mult = Math.min(mult, 0.38);
    if (now < (p.spinUntil || 0)) mult = Math.min(mult, 0.32);
    const sp = RACE_SPEED * mult * (boosting ? RACE_BOOST_MULT : 1);
    p.x = Math.max(RACE_CAR_R, Math.min(g.arenaW - RACE_CAR_R, p.x + Math.cos(p.angle) * sp * dt));
    p.y = Math.max(RACE_CAR_R, Math.min(g.arenaH - RACE_CAR_R, p.y + Math.sin(p.angle) * sp * dt));
    p.inWater = inWater;
  }

  // 차끼리 부드럽게 밀어내기 (완주한 차는 유령이 된다)
  const live = racers.filter(p => !p.finishedAt);
  for (let i = 0; i < live.length; i++) {
    for (let j = i + 1; j < live.length; j++) {
      const a = live[i], bb = live[j];
      const dx = bb.x - a.x, dy = bb.y - a.y;
      const d2 = dx * dx + dy * dy, min = RACE_CAR_R * 2;
      if (d2 > 0.01 && d2 < min * min) {
        const d = Math.sqrt(d2), push = (min - d) / 2;
        const nx = dx / d, ny = dy / d;
        a.x -= nx * push; a.y -= ny * push;
        bb.x += nx * push; bb.y += ny * push;
      }
    }
  }

  // 진행도·랩 계산
  for (const p of racers) {
    if (p.finishedAt) continue;
    const n = t.pts.length;
    let bi = p.trackIdx || 0, bd = Infinity;
    for (let k = -16; k <= 16; k++) {
      const i = ((p.trackIdx + k) % n + n) % n;
      const dx = p.x - t.pts[i][0], dy = p.y - t.pts[i][1];
      const d = dx * dx + dy * dy;
      if (d < bd) { bd = d; bi = i; }
    }
    // 지름길 방지: 한 틱에 트랙 인덱스가 크게 건너뛰면(S자 코너가 겹치는 구간을
    // 가로질러 진행도를 훔치는 것) 그 진행을 무효로 하고 이전 위치를 유지한다.
    const fwd = ((bi - (p.trackIdx || 0)) % n + n) % n;
    const jumped = fwd > 8 && fwd < n - 8;
    if (jumped) { p.trackDist = Math.sqrt(bd); continue; }  // 랩·s 갱신 없이 넘어감
    p.trackIdx = bi; p.trackDist = Math.sqrt(bd);
    const sNow = t.cum[bi];
    if (p.startS == null) p.startS = sNow;   // 출발 지점(형평성 기준)
    if (p.prevS != null) {
      const d = sNow - p.prevS;
      if (d < -t.total / 2) p.crossings++;        // 결승선 앞으로 통과
      else if (d > t.total / 2) p.crossings--;    // 결승선 뒤로 넘어감 (역주행)
    }
    p.prevS = sNow;
    p.raceProgress = p.crossings * t.total + sNow;
    // 완주 = 출발점부터 정확히 RACE_LAPS바퀴만큼 달렸을 때 (출발 격자 위치와 무관하게 공정).
    // 매 틱 검사해야 격자 보정된 완주 지점을 놓치지 않는다.
    if (p.raceProgress - p.startS >= RACE_LAPS * t.total - 5) {
      p.finishedAt = now;
      p.finishRank = ++g.finishCount;
      if (!g.firstFinishAt) {
        g.firstFinishAt = now;
        // 1등이 나오면 남은 시간을 30초로 줄인다 (한 명 때문에 2분 기다리는 일 방지)
        if (room.phaseEndAt > now + RACE_AFTER_FIRST_MS) {
          room.phaseEndAt = now + RACE_AFTER_FIRST_MS;
          broadcast(room, { type: 'phase', state: 'playing', gameType: 'race', endAt: room.phaseEndAt, st: now });
        }
      }
    }
  }

  const allDone = racers.length > 0 && racers.every(p => p.finishedAt);
  if (now >= room.phaseEndAt || allDone || racers.length === 0) { endRace(room); return; }
  sendState(room, now);
}

function endRace(room) {
  const g = room.game;
  const parts = [...room.players.values()].filter(p => !p.waiting);
  const sorted = parts.sort((a, b) => {
    const af = a.finishedAt || Infinity, bf = b.finishedAt || Infinity;
    if (af !== bf) return af - bf;
    return (b.raceProgress || 0) - (a.raceProgress || 0);
  });
  finishGame(room, sorted,
    p => p.finishedAt
      ? ((p.finishedAt - g.startedAt) / 1000).toFixed(1) + '초 완주 🏁'
      : `${Math.max(1, Math.min(RACE_LAPS, p.crossings + 1))}랩에서 종료`,
    p => p.finishedAt ? String(p.finishedAt) : 'dnf' + Math.round(p.raceProgress || 0));
}

// ---------- 설원 러너 ----------
function runTick(room, now, dt) {
  const g = room.game;
  const elapsed = now - g.startedAt;
  const baseSp = RUN_BASE_SPEED + (RUN_MAX_SPEED - RUN_BASE_SPEED) * Math.min(1, elapsed / RUN_RAMP_MS);

  for (const p of room.players.values()) {
    if (!p.alive) continue;
    // 레인 이동: 스틱을 한 번 밀 때마다 1칸 (밀고 있는 동안 반복 안 됨 — 플릭 방식)
    const px = p.dirX;
    if (Math.abs(px) < 0.32) p.lanePush = 0;
    else if (px > 0.45 && p.lanePush !== 1) { p.laneTarget = Math.min(RUN_LANES - 1, p.laneTarget + 1); p.lanePush = 1; }
    else if (px < -0.45 && p.lanePush !== -1) { p.laneTarget = Math.max(0, p.laneTarget - 1); p.lanePush = -1; }
    const dl = p.laneTarget - p.lane, mv = RUN_LANE_SPEED * dt;
    p.lane = Math.abs(dl) <= mv ? p.laneTarget : p.lane + Math.sign(dl) * mv;

    // 점프 높이 (포물선)
    const jt = p.jumpStartAt ? (now - p.jumpStartAt) / RUN_JUMP_MS : 2;
    p.jumpY = jt >= 0 && jt <= 1 ? 4 * RUN_JUMP_H * jt * (1 - jt) : 0;

    // 전진 (비틀거림 감속 · 피버 가속)
    const mult = (now < p.stumbleUntil ? RUN_STUMBLE_MULT : 1) * (now < p.feverUntil ? RUN_FEVER_MULT : 1);
    p.prevDist = p.dist;
    p.dist += baseSp * mult * dt;

    // 장애물: 이번 틱에 지나친 것만 스윕 검사 (포인터가 전진만 해서 한 번씩만 처리됨)
    const obs = g.course.obs;
    while (p.obIdx < obs.length && obs[p.obIdx][0] <= p.prevDist) p.obIdx++;
    for (let i = p.obIdx; i < obs.length && obs[i][0] <= p.dist; i++) {
      const ol = obs[i][1], ot = obs[i][2];
      if (Math.abs(p.lane - ol) > 0.42 || now < p.invUntil) continue;
      if (ot === 0 && p.jumpY >= RUN_CLEAR_H) continue;   // 낮은 블록은 점프로 통과
      p.stumbleUntil = now + RUN_STUMBLE_MS;
      p.invUntil = now + RUN_STUMBLE_MS + 700;            // 연속 충돌 방지 무적
      p.stumbleAt = now;
      p.gauge = 0;                                        // 피버 게이지 리셋 (안 피하면 피버가 안 터진다)
      p.coins = Math.max(0, p.coins - 2);                 // 코인 2개 드랍 — 가만히 코인만 먹는 플레이 방지
      break;
    }

    // 코인: 같은 스윕 방식 — 경쟁이 아니라 각자 수집 (모두가 같은 코인을 먹을 수 있다)
    const cs = g.course.coins;
    while (p.coinIdx < cs.length && cs[p.coinIdx][0] <= p.prevDist) p.coinIdx++;
    for (let i = p.coinIdx; i < cs.length && cs[i][0] <= p.dist; i++) {
      const cl = cs[i][1], ch = cs[i][2];
      if (now < p.stumbleUntil) continue;                    // 비틀거리는 동안엔 못 줍는다
      if (Math.abs(p.lane - cl) > 0.45) continue;
      if (ch === 1 ? p.jumpY < 35 : p.jumpY > 55) continue;  // 공중 코인=점프 중에만, 바닥 코인=지상에서만
      p.coins++; p.lastCoinAt = now;
      if (++p.gauge >= RUN_FEVER_COINS) {
        p.gauge = 0;
        p.feverUntil = now + RUN_FEVER_MS;
        p.invUntil = Math.max(p.invUntil, p.feverUntil);   // 피버 동안 무적 질주
      }
    }

    p.score = Math.round(p.dist / 10) + p.coins * RUN_COIN_SCORE;
  }

  if (now >= room.phaseEndAt) { endRun(room); return; }
  sendState(room, now);
}

function endRun(room) {
  const parts = [...room.players.values()].filter(p => !p.waiting);
  const sorted = parts.sort((a, b) => (b.score || 0) - (a.score || 0));
  finishGame(room, sorted,
    p => `${Math.round(p.dist / 10)}m + 🪙${p.coins} = ${p.score}점`,
    p => String(p.score || 0));
}

// ---------- 사이먼 가라사대 ----------
function startSimonRound(room, now) {
  const g = room.game;
  g.siRound++;
  g.seq.push(Math.floor(Math.random() * 4));
  while (g.seq.length < SIMON_START_LEN) g.seq.push(Math.floor(Math.random() * 4));
  g.siPhase = 'show';
  g.siRevived = false;
  g.showAt = now + 1200;
  g.showEndAt = g.showAt + g.seq.length * SIMON_GAP + 500;
  g.inputEndAt = 0; g.revealEndAt = 0;
  for (const p of room.players.values()) { p.simonIdx = 0; p.simonDone = false; }
  // 패턴은 교사 화면에만 전송 — 학생 폰 개발자도구로는 절대 못 본다
  if (room.hostWs) roomSend(room.hostWs, { type: 'simon_seq', seq: g.seq, showAt: g.showAt, gap: SIMON_GAP, flashMs: SIMON_FLASH });
}
function simonTick(room, now) {
  const g = room.game;
  if (g.siPhase === 'show' && now >= g.showEndAt) {
    g.siPhase = 'input';
    g.inputEndAt = now + g.seq.length * 1300 + 3500;
  } else if (g.siPhase === 'input') {
    const alive = [...room.players.values()].filter(p => p.alive);
    // 조기 진행 판정은 접속 중인 생존자 기준 — 유예 중인 끊긴 학생이 매 라운드 시간을 다 끌지 않게
    const present = alive.filter(p => p.connected);
    const allDone = present.length > 0 && present.every(p => p.simonDone);
    if (allDone || now >= g.inputEndAt) {
      // 시간 안에 다 못 누른 생존자도 탈락
      for (const p of alive) if (!p.simonDone) { p.alive = false; p.deadAt = now; p.outRound = g.siRound; }
      const nowAlive = [...room.players.values()].filter(p => p.alive);
      // 전원 탈락이면 전원 부활 (다음 라운드 재도전 — OX와 같은 규칙)
      if (nowAlive.length === 0 && g.startingCount >= 2) {
        for (const p of room.players.values()) if (!p.waiting && p.connected) { p.alive = true; p.deadAt = 0; }
        g.siRevived = true;
      }
      g.siPhase = 'reveal';
      g.revealEndAt = now + 2600;
    }
  } else if (g.siPhase === 'reveal' && now >= g.revealEndAt) {
    const nowAlive = [...room.players.values()].filter(p => p.alive);
    if ((g.startingCount >= 2 && nowAlive.length <= 1) || g.siRound >= SIMON_MAX_ROUND || nowAlive.length === 0) {
      endSimon(room); return;
    }
    startSimonRound(room, now);
  }
  sendState(room, now);
}
function endSimon(room) {
  const g = room.game;
  const parts = [...room.players.values()].filter(p => !p.waiting);
  const sorted = parts.sort((a, b) => {
    if (!!a.alive !== !!b.alive) return a.alive ? -1 : 1;
    return (b.outRound || 0) - (a.outRound || 0);
  });
  finishGame(room, sorted,
    p => p.alive ? `${g.siRound}라운드 정복 🏆` : `${p.outRound || 1}라운드에서 탈락`,
    p => p.alive ? 'win' : 'r' + (p.outRound || 0));
}

// ---------- 침팬지 테스트 ----------
function startChimpRound(room, now) {
  const g = room.game;
  g.chRound++;
  g.chN = 3 + g.chRound;                          // 4 → 11개
  // 서로 겹치지 않게 셀 배치
  const cells = [];
  let guard = 0;
  while (cells.length < g.chN && guard++ < 600) {
    const x = 90 + Math.random() * (g.arenaW - 180);
    const y = 90 + Math.random() * (g.arenaH - 180);
    if (cells.every(c => Math.hypot(c[0] - x, c[1] - y) > 150)) cells.push([Math.round(x), Math.round(y)]);
  }
  g.chN = cells.length;                            // 배치 실패 시 실제 개수로
  g.cells = cells;
  // 숫자 1..n을 셀에 무작위 배정 — 셀 배열 순서로는 숫자를 유추할 수 없다
  g.nums = [...Array(cells.length).keys()].map(i => i + 1).sort(() => Math.random() - 0.5);
  g.chPhase = 'memo';
  g.memoEndAt = now + 1600 + cells.length * 320;
  g.inputEndAt = 0; g.revealEndAt = 0;
  for (const p of room.players.values()) { p.chIdx = 0; p.chFail = false; p.chDoneAt = 0; }
  // 숫자는 교사 화면에만 — 학생은 TV를 보고 외워야 한다
  if (room.hostWs) roomSend(room.hostWs, { type: 'chimp_nums', nums: g.nums, memoEndAt: g.memoEndAt });
}
function chimpTick(room, now) {
  const g = room.game;
  if (g.chPhase === 'memo' && now >= g.memoEndAt) {
    g.chPhase = 'input';
    g.inputEndAt = now + g.chN * 1800 + 2500;
  } else if (g.chPhase === 'input') {
    const actives = [...room.players.values()].filter(p => p.alive && p.connected);
    const allDone = actives.length > 0 && actives.every(p => p.chFail || p.chIdx >= g.chN);
    if (allDone || now >= g.inputEndAt) {
      g.chPhase = 'reveal';
      g.revealEndAt = now + 3000;
    }
  } else if (g.chPhase === 'reveal' && now >= g.revealEndAt) {
    if (g.chRound >= CHIMP_ROUNDS) { endScoreGame(room, '점'); return; }
    startChimpRound(room, now);
  }
  sendState(room, now);
}

// ---------- 순간 포착 ----------
function buildFlashQs() {
  const qs = [];
  for (let i = 0; i < FLASH_QS; i++) {
    const pool = [...FLASH_POOL].sort(() => Math.random() - 0.5);
    const k = 4 + Math.floor(Math.random() * 3);            // 화면에 나올 이모지 종류 4~6
    const scene = pool.slice(0, k).map(e => [e, 1 + Math.floor(Math.random() * 3)]);
    const absent = pool.slice(k);
    const typ = Math.floor(Math.random() * 4);
    let q, choices, correct;
    if (typ === 0) {          // 특정 그림 개수
      const pickI = Math.floor(Math.random() * scene.length);
      const emo = scene[pickI][0], cnt = scene[pickI][1];
      q = `${emo} 는 몇 개였을까?`;
      const set = new Set([cnt]);
      while (set.size < 4) set.add(Math.max(0, cnt + Math.floor(Math.random() * 7) - 3));
      choices = [...set].sort(() => Math.random() - 0.5).map(String);
      correct = choices.indexOf(String(cnt));
    } else if (typ === 1) {   // 없었던 것
      const wrong = [...scene].sort(() => Math.random() - 0.5).slice(0, 3).map(s => s[0]);
      const ans = absent[0];
      choices = [...wrong, ans].sort(() => Math.random() - 0.5);
      correct = choices.indexOf(ans);
      q = '화면에 없었던 것은?';
    } else if (typ === 2) {   // 있었던 것
      const ans = scene[Math.floor(Math.random() * scene.length)][0];
      choices = [...absent.slice(0, 3), ans].sort(() => Math.random() - 0.5);
      correct = choices.indexOf(ans);
      q = '화면에 있었던 것은?';
    } else {                  // 전체 개수
      const total = scene.reduce((s, it) => s + it[1], 0);
      q = '그림은 모두 몇 개였을까?';
      const set = new Set([total]);
      while (set.size < 4) set.add(Math.max(1, total + Math.floor(Math.random() * 9) - 4));
      choices = [...set].sort(() => Math.random() - 0.5).map(String);
      correct = choices.indexOf(String(total));
    }
    qs.push({ scene, q, choices, correct });
  }
  return qs;
}
function startFlashQ(room, now) {
  const g = room.game;
  g.fPhase = 'memo';
  g.memoEndAt = now + FLASH_MEMO_MS + 900;
  for (const p of room.players.values()) { p.qAnswer = -1; p.qAnswerAt = 0; p.qGain = 0; }
  const Q = g.questions[g.fIdx];
  // 장면은 교사 화면에만 — 문제가 나올 때까지 폰에는 아무것도 없다
  if (room.hostWs) roomSend(room.hostWs, { type: 'flash_scene', scene: Q.scene, memoEndAt: g.memoEndAt });
}
function flashTick(room, now) {
  const g = room.game;
  const Q = g.questions[g.fIdx];
  if (g.fPhase === 'memo' && now >= g.memoEndAt) {
    g.fPhase = 'show';
    g.qEndAt = now + FLASH_TIME_MS;
  } else if (g.fPhase === 'show') {
    const parts = [...room.players.values()].filter(p => !p.waiting && p.connected);
    const allAns = parts.length > 0 && parts.every(p => p.qAnswer >= 0);
    if (allAns || now >= g.qEndAt) {
      // 채점: 정답 100 + 남은 시간 비례 보너스 최대 100 (퀴즈쇼와 동일)
      for (const p of room.players.values()) {
        if (p.waiting) continue;
        if (p.qAnswer === Q.correct) {
          const left = Math.max(0, g.qEndAt - (p.qAnswerAt || g.qEndAt));
          p.qGain = 100 + Math.round(Math.min(100, left / FLASH_TIME_MS * 100));
          p.score += p.qGain;
        } else p.qGain = 0;
      }
      g.fPhase = 'reveal';
      g.revealEndAt = now + 5200;
    }
  } else if (g.fPhase === 'reveal' && now >= g.revealEndAt) {
    g.fIdx++;
    if (g.fIdx >= g.questions.length) { endScoreGame(room, '점'); return; }
    startFlashQ(room, now);
  }
  sendState(room, now);
}

// ---------- 같은 그림 찾기 ----------
function pairsTick(room, now) {
  const g = room.game;
  for (const p of room.players.values()) {
    if (p.waiting) continue;
    // 두 장 뒤집힘 → 650ms 열어 보여준 뒤 판정
    if (p.pFlipB >= 0 && now >= p.pResolveAt) {
      if (g.faces[p.pFlipA] === g.faces[p.pFlipB]) {
        p.pMask |= (1 << p.pFlipA) | (1 << p.pFlipB);
        p.pPairs++;
        if (p.pPairs >= PAIRS_TOTAL / 2 && !p.pFinAt) { p.pFinAt = now; g.finishedN++; }
      }
      p.pFlipA = -1; p.pFlipB = -1;
    }
    p.score = p.pPairs * 100 - p.pAttempts * 2
      + (p.pFinAt ? Math.round(Math.max(0, room.phaseEndAt - p.pFinAt) / 1000) * 4 : 0);   // 완주 보너스 = 남긴 초×4
  }
  const actives = [...room.players.values()].filter(p => !p.waiting && p.connected);
  if (now >= room.phaseEndAt || (actives.length > 0 && actives.every(p => p.pFinAt))) { endPairs(room); return; }
  sendState(room, now);
}
function endPairs(room) {
  const parts = [...room.players.values()].filter(p => !p.waiting);
  const sorted = parts.sort((a, b) => {
    if ((b.pPairs || 0) !== (a.pPairs || 0)) return (b.pPairs || 0) - (a.pPairs || 0);
    const af = a.pFinAt || Infinity, bf = b.pFinAt || Infinity;
    if (af !== bf) return af - bf;
    return (a.pAttempts || 0) - (b.pAttempts || 0);
  });
  finishGame(room, sorted,
    p => `${p.pPairs}쌍 · 시도 ${p.pAttempts}회${p.pFinAt ? ' 🏁' : ''}`,
    p => `${p.pPairs}|${p.pFinAt || 0}|${p.pAttempts}`);
}

// ---------- 블록 배틀 (실시간 테트리스) ----------
// 서버 권위: 보드·조각·중력·라인클리어·공격 전부 서버 계산. 클라는 버튼 입력만 보낸다.
function tetInitPlayer(p) {
  p.tBoard = new Uint8Array(TET_W * TET_H);   // 0=빈칸, 1~7=색(조각+1), 8=쓰레기
  p.tBag = [];                                 // 7-bag 셔플
  p.tPiece = -1; p.tRot = 0; p.tX = 3; p.tY = 0;
  p.tNext = tetDraw(p);
  tetSpawn(p);
  p.tNextFallAt = 0; p.tLockAt = 0; p.tSoft = false;
  p.tLines = 0; p.tSent = 0; p.tPendingGarbage = 0;
  p.tClearFx = 0;                              // 마지막 클리어 줄 수(연출용, 호스트 전송 후 리셋)
  p.tBoardStr = tetPackBoard(p);               // 보드는 고정 때만 바뀜 — 문자열 캐시로 매 틱 패킹 방지
  p.score = 0;
}
function tetPackBoard(p) {
  let s = '';
  for (let i = 0; i < p.tBoard.length; i++) s += p.tBoard[i];
  return s;
}
function tetDraw(p) {
  if (!p.tBag.length) p.tBag = [0, 1, 2, 3, 4, 5, 6].sort(() => Math.random() - 0.5);
  return p.tBag.pop();
}
function tetSpawn(p) {
  p.tPiece = p.tNext; p.tNext = tetDraw(p);
  p.tRot = 0; p.tX = 3; p.tY = -1;             // 4x4 박스가 위 1줄 걸치고 시작
  p.tSoft = false; p.tLockAt = 0;
}
function tetFits(p, x, y, rot) {
  const cells = TET_SHAPES[p.tPiece][rot];
  for (const [cx, cy] of cells) {
    const bx = x + cx, by = y + cy;
    if (bx < 0 || bx >= TET_W || by >= TET_H) return false;
    if (by >= 0 && p.tBoard[by * TET_W + bx]) return false;
  }
  return true;
}
function tetLock(room, p, now) {
  const cells = TET_SHAPES[p.tPiece][p.tRot];
  let topOut = false;
  for (const [cx, cy] of cells) {
    const by = p.tY + cy;
    if (by < 0) { topOut = true; continue; }
    p.tBoard[by * TET_W + (p.tX + cx)] = p.tPiece + 1;
  }
  // 줄 지우기
  let cleared = 0;
  for (let y = TET_H - 1; y >= 0; y--) {
    let full = true;
    for (let x = 0; x < TET_W; x++) if (!p.tBoard[y * TET_W + x]) { full = false; break; }
    if (full) {
      cleared++;
      p.tBoard.copyWithin(TET_W, 0, y * TET_W);   // 위 전체를 한 줄 아래로
      p.tBoard.fill(0, 0, TET_W);
      y++;                                         // 같은 y 재검사 (위에서 내려온 줄)
    }
  }
  if (cleared) {
    p.tLines += cleared;
    p.score += [0, 100, 300, 500, 800][cleared] * (1 + (room.game.stage - 1) * 0.1) | 0;
    p.tClearFx = cleared;
    // 공격: 2줄부터 랜덤 생존 상대에게 쓰레기 줄
    const atk = TET_ATTACK[cleared] || 0;
    if (atk > 0) {
      const targets = [...room.players.values()].filter(q => q.alive && q !== p);
      if (targets.length) {
        const t = targets[Math.floor(Math.random() * targets.length)];
        t.tPendingGarbage = Math.min(8, (t.tPendingGarbage || 0) + atk);
        t.tAttackedBy = p.nick;
      }
      p.tSent += atk;
    }
  }
  // 대기 중인 쓰레기 줄 올리기 (내 조각이 고정된 직후에)
  if (p.tPendingGarbage > 0) {
    const n = p.tPendingGarbage; p.tPendingGarbage = 0;
    // 위 n줄에 블록이 있으면 밀려서 죽는다 — 올리기 전 검사
    for (let y = 0; y < n * TET_W; y++) if (p.tBoard[y]) topOut = true;
    p.tBoard.copyWithin(0, n * TET_W);                       // 전체를 n줄 위로
    for (let i = 0; i < n; i++) {
      const y = TET_H - 1 - i, hole = Math.floor(Math.random() * TET_W);
      for (let x = 0; x < TET_W; x++) p.tBoard[y * TET_W + x] = x === hole ? 0 : 8;
    }
    p.tGarbAt = now;                                         // 연출용
  }
  p.tBoardStr = tetPackBoard(p);               // 보드가 바뀌었으니 캐시 갱신
  if (topOut) { p.alive = false; p.deadAt = now; return; }
  tetSpawn(p);
  if (!tetFits(p, p.tX, p.tY, p.tRot)) { p.alive = false; p.deadAt = now; return; }
  p.tNextFallAt = now + tetGrav(room, p);
}
function tetGrav(room, p) {
  const g = Math.max(TET_MIN_GRAV, TET_BASE_GRAV * Math.pow(TET_GRAV_DECAY, room.game.stage - 1));
  return p.tSoft ? Math.min(TET_SOFT_GRAV, g) : g;
}
function tetrisTick(room, now) {
  const g = room.game;
  // 단계 상승 — 루즈해질 틈 없이 금방 어려워진다
  if (now >= g.nextStageAt) { g.stage++; g.nextStageAt = now + TET_STAGE_MS; }

  for (const p of room.players.values()) {
    if (!p.alive || p.waiting) continue;
    if (p.tPiece < 0) continue;
    // 중력
    while (now >= p.tNextFallAt) {
      if (tetFits(p, p.tX, p.tY + 1, p.tRot)) {
        p.tY++; p.tNextFallAt += tetGrav(room, p); p.tLockAt = 0;
      } else {
        if (!p.tLockAt) p.tLockAt = now + TET_LOCK_MS;   // 바닥 유예 시작
        p.tNextFallAt = now + tetGrav(room, p);
        break;
      }
    }
    // 고정 판정 — 유예가 끝났는데 여전히 아래가 막혀 있으면 고정
    if (p.tLockAt && now >= p.tLockAt) {
      if (!tetFits(p, p.tX, p.tY + 1, p.tRot)) tetLock(room, p, now);
      else p.tLockAt = 0;                               // 유예 중 아래가 뚫렸으면 계속 낙하
    }
  }

  const alive = [...room.players.values()].filter(p => p.alive);
  const total = [...room.players.values()].filter(p => !p.waiting).length;
  if ((total >= 2 && alive.length <= 1) || (total === 1 && alive.length === 0) || now >= room.phaseEndAt) {
    endTetris(room, now); return;
  }
  sendState(room, now);
}
function endTetris(room, now) {
  const g = room.game;
  const parts = [...room.players.values()].filter(p => !p.waiting);
  const sorted = parts.sort((a, b) => {
    if (a.alive !== b.alive) return a.alive ? -1 : 1;
    if (a.alive) return (b.score || 0) - (a.score || 0);   // 시간 종료로 복수 생존 시 점수순
    return (b.deadAt || 0) - (a.deadAt || 0);
  });
  finishGame(room, sorted, p => {
    const t = p.alive ? '생존! ' : '';
    return `${t}${p.tLines || 0}줄 · ${p.score || 0}점${p.tSent ? ` · 공격 ${p.tSent}줄` : ''}`;
  }, p => p.alive ? `a${p.score}` : String(p.deadAt));
}

// ---------- 그림 퀴즈 ----------
// 흐름: pick(방장이 출제자 지목) → write(출제자가 답 입력) → draw(그리기+맞히기) → reveal → pick…
// 정답은 서버에만 저장, reveal 때만 전송 (개발자도구 컨닝 방지)
function drawTick(room, now) {
  const g = room.game;
  if (g.dPhase === 'write') {
    const drawer = room.players.get(g.drawer);
    // 출제자가 시간 안에 답을 못 정했거나 나가버림 → 라운드 무효, 다시 지목
    if (now >= g.writeEndAt || !drawer || !drawer.connected) {
      g.dPhase = 'pick'; g.drawer = null; g.answer = ''; g.strokes = [];
    }
  } else if (g.dPhase === 'draw') {
    const drawer = room.players.get(g.drawer);
    const guessers = [...room.players.values()].filter(p => !p.waiting && p.id !== g.drawer && p.connected);
    const allDone = guessers.length > 0 && guessers.every(p => p.dGuessed);
    if (!drawer || !drawer.connected || now >= g.drawEndAt || allDone) {
      g.dPhase = 'reveal'; g.revealEndAt = now + DRAW_REVEAL_MS;
    }
  } else if (g.dPhase === 'reveal' && now >= g.revealEndAt) {
    if (g.round >= DRAW_MAX_ROUNDS) { endDraw(room); return; }
    g.dPhase = 'pick'; g.drawer = null; g.answer = ''; g.strokes = [];
  }
  sendState(room, now);
}
function endDraw(room) {
  const parts = [...room.players.values()].filter(p => !p.waiting);
  const sorted = parts.sort((a, b) => (b.score || 0) - (a.score || 0));
  finishGame(room, sorted,
    p => `${p.score || 0}점${room.game.drawnIds.has(p.id) ? ' 🎨' : ''}`,
    p => String(p.score || 0));
}
// 그리기 이벤트를 출제자 빼고 전원에게 (출제자는 자기 화면에 이미 그렸음)
function drawRelay(room, drawerId, obj) {
  if (room.hostWs && room.hostWs.readyState === 1) room.hostWs.send(JSON.stringify(obj));
  for (const p of room.players.values())
    if (p.ws && p.id !== drawerId && p.ws.readyState === 1) p.ws.send(JSON.stringify(obj));
}

// 점수순 공통 종료 (침팬지·순간 포착)
function endScoreGame(room, unit) {
  const parts = [...room.players.values()].filter(p => !p.waiting);
  const sorted = parts.sort((a, b) => (b.score || 0) - (a.score || 0));
  finishGame(room, sorted, p => `${p.score}${unit}`, p => String(p.score || 0));
}

// ---------- 공통 종료·상태 ----------
function finishGame(room, sorted, labelOf, keyOf) {
  clearInterval(room.timer); room.timer = null;
  room.state = 'result';
  let rank = 0, prevKey = null;
  const ranking = sorted.map((p, i) => {
    const key = keyOf(p);
    if (key !== prevKey) { rank = i + 1; prevKey = key; }
    return { id: p.id, nick: p.nick, ci: p.ci, rank, label: labelOf(p) };
  });
  broadcast(room, { type: 'result', gameType: room.gameType, ranking });
  sendRoster(room);
}

function sendState(room, now) {
  const g = room.game;
  const type = room.gameType;
  if (type === 'quiz') {
    const Q = g.questions[g.qIdx];
    const parts = [...room.players.values()].filter(p => !p.waiting);
    broadcast(room, {
      type: 'state', mode: 'quiz', st: now,
      qPhase: g.qPhase || 'idle', qIdx: g.qIdx, qTotal: g.questions.length, cat: g.quizCat,
      // 카운트다운(idle) 중에는 문제를 미리 보내지 않는다
      q: g.qPhase === 'idle' ? '' : (Q ? Q.q : ''),
      choices: g.qPhase === 'idle' ? [] : (Q ? Q.choices : []),
      timeLeft: g.qPhase === 'show' ? Math.max(0, g.qEndAt - now) : 0,
      timeTotal: QUIZ_TIME_MS,
      answered: parts.filter(p => p.qAnswer >= 0).length,
      partCount: parts.length,
      // 정답·선택 분포는 공개 시점에만 (미리 보내면 폰 개발자도구로 컨닝 가능)
      correct: g.qPhase === 'reveal' && Q ? Q.correct : undefined,
      counts: g.qPhase === 'reveal' && Q
        ? [0, 1, 2, 3].map(i => parts.filter(p => p.qAnswer === i).length) : undefined,
      // [id, 총점, 답했나, 이번 문제 득점(공개 때만), 내가 고른 번호(공개 때만)]
      scores: parts.map(p => [p.id, p.score, p.qAnswer >= 0 ? 1 : 0,
        g.qPhase === 'reveal' ? (p.qGain || 0) : 0,
        g.qPhase === 'reveal' ? (p.qAnswer != null ? p.qAnswer : -1) : -1]),
    });
    return;
  }
  if (type === 'simon') {
    const g2 = room.game;
    broadcast(room, {
      type: 'state', mode: 'simon', st: now,
      siPhase: g2.siPhase || 'idle', round: g2.siRound || 0, seqLen: (g2.seq || []).length,
      showAt: g2.showAt || 0, gap: SIMON_GAP, flashMs: SIMON_FLASH,
      inputEndAt: g2.inputEndAt || 0, revealEndAt: g2.revealEndAt || 0,
      aliveN: [...room.players.values()].filter(p => p.alive).length,
      doneN: [...room.players.values()].filter(p => p.alive && p.simonDone).length,
      revived: !!g2.siRevived,
      players: [...room.players.values()].map(p =>
        [p.id, p.alive ? 1 : 0, p.waiting ? 1 : 0, p.simonDone ? 1 : 0, p.simonIdx || 0, p.outRound || 0]),
    });
    return;
  }
  if (type === 'chimp') {
    broadcast(room, {
      type: 'state', mode: 'chimp', st: now,
      chPhase: g.chPhase || 'idle', round: g.chRound || 0, totalRounds: CHIMP_ROUNDS, n: g.chN || 0,
      arena: { w: g.arenaW, h: g.arenaH },
      cells: g.cells || [],
      nums: g.chPhase === 'reveal' ? g.nums : undefined,   // 숫자는 공개 시점에만 전원 전송
      memoEndAt: g.memoEndAt || 0, inputEndAt: g.inputEndAt || 0, revealEndAt: g.revealEndAt || 0,
      players: [...room.players.values()].map(p =>
        [p.id, p.alive ? 1 : 0, p.waiting ? 1 : 0, p.score || 0, p.chIdx || 0, p.chFail ? 1 : 0,
         (p.chIdx || 0) >= (g.chN || 99) ? 1 : 0]),
    });
    return;
  }
  if (type === 'flash') {
    const Q = g.questions[g.fIdx];
    const parts = [...room.players.values()].filter(p => !p.waiting);
    const open = g.fPhase === 'show' || g.fPhase === 'reveal';
    broadcast(room, {
      type: 'state', mode: 'flash', st: now,
      fPhase: g.fPhase || 'idle', qIdx: g.fIdx, qTotal: g.questions.length,
      q: open && Q ? Q.q : '',
      choices: open && Q ? Q.choices : [],
      timeLeft: g.fPhase === 'show' ? Math.max(0, g.qEndAt - now)
        : g.fPhase === 'memo' ? Math.max(0, g.memoEndAt - now) : 0,
      timeTotal: FLASH_TIME_MS,
      answered: parts.filter(p => p.qAnswer >= 0).length,
      partCount: parts.length,
      correct: g.fPhase === 'reveal' && Q ? Q.correct : undefined,
      counts: g.fPhase === 'reveal' && Q ? [0, 1, 2, 3].map(i => parts.filter(p => p.qAnswer === i).length) : undefined,
      scene: g.fPhase === 'reveal' && Q ? Q.scene : undefined,   // 장면은 정답 공개 때만 전원에게
      scores: parts.map(p => [p.id, p.score, p.qAnswer >= 0 ? 1 : 0,
        g.fPhase === 'reveal' ? (p.qGain || 0) : 0,
        g.fPhase === 'reveal' ? (p.qAnswer != null ? p.qAnswer : -1) : -1]),
    });
    return;
  }
  if (type === 'draw') {
    // 아무것도 안 움직이는 대기 시간이 길다 — 7Hz면 타이머바에 충분
    if (g.dStateAt && now - g.dStateAt < 150) return;
    g.dStateAt = now;
    const parts = [...room.players.values()].filter(p => !p.waiting);
    broadcast(room, {
      type: 'state', mode: 'draw', st: now,
      dPhase: g.dPhase || 'pick', round: g.round || 0, drawer: g.drawer,
      timeLeft: g.dPhase === 'write' ? Math.max(0, g.writeEndAt - now)
        : g.dPhase === 'draw' ? Math.max(0, g.drawEndAt - now)
        : g.dPhase === 'reveal' ? Math.max(0, g.revealEndAt - now) : 0,
      timeTotal: g.dPhase === 'write' ? DRAW_WRITE_MS : g.dPhase === 'draw' ? DRAW_ROUND_MS : DRAW_REVEAL_MS,
      correctN: parts.filter(p => p.dGuessed).length,
      guessN: Math.max(0, parts.filter(p => p.id !== g.drawer).length),
      ansLen: g.dPhase === 'draw' ? g.answer.length : 0,       // 글자 수 힌트
      answer: g.dPhase === 'reveal' ? g.answer : undefined,    // 정답은 공개 시점에만!
      // [id, 점수, 이번 판 맞힘, 출제 이력, 접속]
      players: parts.map(p => [p.id, p.score || 0, p.dGuessed ? 1 : 0,
        g.drawnIds.has(p.id) ? 1 : 0, p.connected ? 1 : 0]),
    });
    return;
  }
  if (type === 'tetris') {
    const parts = [...room.players.values()].filter(p => !p.waiting);
    const base = {
      type: 'state', mode: 'tetris', st: now, stage: g.stage,
      timeLeft: room.state === 'playing' && room.phaseEndAt ? Math.max(0, room.phaseEndAt - now) : TET_MAX_MS,
      aliveN: parts.filter(p => p.alive).length, totalN: parts.length,
    };
    // 학생: 자기 보드+조각만 매 틱 (부드러운 조작감, ~300B)
    for (const p of room.players.values()) {
      if (!p.ws || p.waiting || !p.tBoard) continue;
      roomSend(p.ws, {
        ...base,
        me: [p.tBoardStr, p.tPiece, p.tRot, p.tX, p.tY, p.tNext,
             p.tPendingGarbage || 0, p.score || 0, p.tLines || 0, p.alive ? 1 : 0, p.tClearFx || 0],
        atkBy: p.tAttackedBy || undefined,
      });
      p.tAttackedBy = null;
    }
    // 교사 TV: 전원 보드 — 5Hz 스로틀 (40명×250B×20Hz는 Render 무료 티어에 과함)
    if (room.hostWs && (!g.tHostAt || now - g.tHostAt >= 200)) {
      g.tHostAt = now;
      roomSend(room.hostWs, {
        ...base,
        boards: parts.map(p => [p.id, p.alive ? 1 : 0, p.score || 0, p.tLines || 0,
          p.tBoardStr || '', p.tPiece, p.tRot, p.tX, p.tY, p.tClearFx || 0, p.tSent || 0]),
      });
      for (const p of parts) p.tClearFx = 0;   // 연출 플래그는 호스트 전송 후 소거
    }
    return;
  }
  if (type === 'pairs') {
    // 배치가 전원 동일이라 남의 pMask·pFlipA/pFlipB를 보면 짝을 유추할 수 있다(WS 프레임 관찰 치팅).
    // 비밀 필드는 본인 행에만 담고, 타인·교사에게는 집계(시도·쌍·완주)만 보낸다.
    const base = {
      type: 'state', mode: 'pairs', st: now,
      timeLeft: room.state === 'playing' && room.phaseEndAt ? Math.max(0, room.phaseEndAt - now) : PAIRS_MS,
      timeTotal: PAIRS_MS,
      total: PAIRS_TOTAL, cols: 4, rows: 5,
      finishedN: g.finishedN || 0,
    };
    const pubRows = [...room.players.values()].map(p =>
      [p.id, p.alive ? 1 : 0, p.waiting ? 1 : 0, p.score || 0,
       0, -1, -1,
       p.pAttempts || 0, p.pPairs || 0, p.pFinAt ? 1 : 0]);
    if (room.hostWs) roomSend(room.hostWs, { ...base, players: pubRows });
    for (const p of room.players.values()) {
      if (!p.ws) continue;
      const mine = [p.id, p.alive ? 1 : 0, p.waiting ? 1 : 0, p.score || 0,
        p.pMask || 0, p.pFlipA != null ? p.pFlipA : -1, p.pFlipB != null ? p.pFlipB : -1,
        p.pAttempts || 0, p.pPairs || 0, p.pFinAt ? 1 : 0];
      roomSend(p.ws, { ...base, players: pubRows.map(r => r[0] === p.id ? mine : r) });
    }
    return;
  }
  if (type === 'word' || type === 'cho') {
    broadcast(room, {
      type: 'state', mode: type, st: now,
      round: g.round, totalRounds: WORD_ROUNDS,
      word: g.wordPhase === 'show' ? (type === 'cho' ? g.pattern : g.word) : null,
      category: type === 'cho' ? g.category : undefined,
      claimed: type === 'cho' && g.claimed ? g.claimed.map(c => [c.w, c.id]) : undefined,
      answerCount: type === 'cho' && g.answers ? g.answers.size : 0,
      freeMode: type === 'cho' ? CHO_FREE_CATS.has(g.category) : undefined,
      // 아무도 못 맞힌 라운드에 정답을 보여주기 위한 예시 (쉬는 시간에만)
      sample: type === 'cho' && g.wordPhase === 'break' && g.answers ? [...g.answers].slice(0, 3) : undefined,
      wordPhase: g.wordPhase || 'idle',
      timeLeft: g.wordPhase === 'show' ? Math.max(0, g.roundEndAt - now) : 0,
      roundTotal: type === 'cho' ? CHO_ROUND_MS : WORD_TIME_MS,
      scores: [...room.players.values()].filter(p => !p.waiting).map(p => {
        const ord = g.correctOrder.indexOf(p.id);
        return [p.id, p.score, p.wordDone ? ord + 1 : 0];
      }),
    });
    return;
  }
  // 레이싱: 진행도 순으로 현재 등수 매기기 (완주자는 완주 순서 고정)
  let raceOrder = null;
  if (type === 'race') {
    raceOrder = new Map();
    [...room.players.values()].filter(p => !p.waiting)
      .sort((a, bb) => {
        const af = a.finishedAt || Infinity, bf = bb.finishedAt || Infinity;
        if (af !== bf) return af - bf;
        return (bb.raceProgress || 0) - (a.raceProgress || 0);
      })
      .forEach((p, i) => raceOrder.set(p.id, i + 1));
  }
  const msg = {
    type: 'state', mode: type, st: now,
    arena: { w: g.arenaW, h: g.arenaH },
    timeLeft: room.state === 'playing' && room.phaseEndAt ? Math.max(0, room.phaseEndAt - now) : (g.roundMs || 0),
    players: [...room.players.values()].map(p => {
      const extra = type === 'tag' ? (p.infected ? 1 : 0)
        : (type === 'coin' || type === 'mos' || type === 'claw' || type === 'gala' || type === 'sadari' || type === 'timing' || type === 'run') ? p.score
        : type === 'race' ? (raceOrder ? raceOrder.get(p.id) || 0 : 0) : 0;
      const row = [p.id, Math.round(p.x), Math.round(p.y), p.alive ? 1 : 0, p.waiting ? 1 : 0, extra];
      // 스모: 대시 중 / 대시 쿨타임(0.1초 단위) / 최근 충돌
      if (type === 'sumo') {
        row.push(now < (p.dashUntil || 0) ? 1 : 0,
                 Math.max(0, Math.ceil(((p.dashReadyAt || 0) - now) / 100)),
                 now - (p.bumpAt || 0) < 220 ? 1 : 0);
      }
      // 의자 뺏기: 앉았는지
      if (type === 'chair') row.push(p.satChair != null ? 1 : 0);
      // 사다리·통아저씨: 다 골랐는지 (뭘 골랐는지는 공개 시점에만)
      if (type === 'sadari') row.push(p.pick >= 0 ? 1 : 0);
      if (type === 'pirate') row.push(p.picks.length >= g.knives ? 1 : 0);
      if (type === 'timing') row.push(p.tapAt > 0 ? 1 : 0);
      // 러너: 거리·레인(×100)·점프높이·피버·비틀거림·코인·피버게이지
      if (type === 'run') {
        row.push(Math.round(p.dist || 0), Math.round((p.lane != null ? p.lane : 1) * 100),
                 Math.round(p.jumpY || 0),
                 now < (p.feverUntil || 0) ? 1 : 0,
                 now - (p.stumbleAt || 0) < 600 ? 1 : 0,
                 p.coins || 0, p.gauge || 0);
      }
      // 폭탄 밟은 직후 1초간 "0원!" 연출
      if (type === 'coin') row.push(now - (p.lostAt || 0) < 1000 ? 1 : 0);
      // 파리채 위치·최근 명중 표시
      if (type === 'mos') {
        row.push(now - (p.swatAt || 0) < 260 ? 1 : 0,
                 Math.round(p.swatX || 0), Math.round(p.swatY || 0),
                 now - (p.hitAt || 0) < 500 ? (p.hitGold ? 2 : 1) : 0);
      }
      // 집게 위치·상태
      if (type === 'claw') {
        row.push(Math.round(p.clawX || 0),
                 p.clawState === 'drop' ? Math.round(Math.min(1, p.clawT / CLAW_DROP_MS) * 100) : 0,
                 now - (p.gotAt || 0) < 700 ? (p.clawGot || 0) : 0,
                 now - (p.missAt || 0) < 500 ? 1 : 0);
      }
      // 레이싱: 방향각·랩·부스터·완주 순위·스핀/물 상태
      if (type === 'race') {
        // 랩 표시는 출발점부터 달린 거리 기준 (격자 보정과 일관되게)
        const lapNow = p.startS == null ? 1
          : Math.max(1, Math.min(RACE_LAPS, Math.floor((p.raceProgress - p.startS) / (g.track.total || 1)) + 1));
        row.push(Math.round((p.angle || 0) * 180 / Math.PI),
                 lapNow,
                 p.boostsLeft || 0,
                 now < (p.boostUntil || 0) ? 1 : 0,
                 p.finishedAt ? (p.finishRank || 0) : 0,
                 now < (p.spinUntil || 0) ? 1 : (p.inWater ? 2 : 0));
      }
      return row;
    }),
  };
  if (type === 'bomb') msg.bombs = g.bombs.map(b => {
    const boom = now >= b.explodeAt;
    const prog = boom ? (now - b.explodeAt) / BOMB_BOOM_MS
      : (now - (b.explodeAt - BOMB_WARN_MS)) / BOMB_WARN_MS;
    return [Math.round(b.x), Math.round(b.y), Math.round(b.r), boom ? 1 : 0, Math.round(prog * 100)];
  });
  if (type === 'coin') {
    msg.coins = g.coins.map(c => [Math.round(c.x), Math.round(c.y), c.v]);
    msg.mines = g.mines.map(m => [Math.round(m.x), Math.round(m.y), now >= m.liveAt ? 1 : 0]);
  }
  if (type === 'mos') msg.mos = g.mos.map(m => [Math.round(m.x), Math.round(m.y), m.gold ? 1 : 0]);
  if (type === 'gala') {
    msg.wave = g.wave;
    msg.enemies = g.enemies.map(e => [Math.round(e.x), Math.round(e.y), e.elite ? 1 : 0, e.mode === 'dive' ? 1 : 0]);
    // 총알은 [x1,y1,x2,y2,...] 평탄한 배열로 (용량 절약)
    const pb = [], eb = [];
    for (const bl of g.pb) { pb.push(Math.round(bl.x), Math.round(bl.y)); }
    for (const bl of g.eb) { eb.push(Math.round(bl.x), Math.round(bl.y)); }
    msg.pb = pb; msg.eb = eb;
    if (g.kills.length) msg.kills = g.kills;
  }
  if (type === 'dodge') {
    const db = [];
    for (const bl of g.bullets) { db.push(Math.round(bl.x), Math.round(bl.y)); }
    msg.db = db;
    msg.elapsed = Math.round((now - g.startedAt) / 1000);
  }
  if (type === 'claw') msg.dolls = g.dolls.map(d => [Math.round(d.x), Math.round(d.y), d.v]);
  if (type === 'sumo') msg.ring = Math.round(g.ringR);
  if (type === 'chair') {
    msg.cphase = g.cphase;
    msg.cround = g.cRound;
    msg.chairs = g.chairs.map(c => [Math.round(c.x), Math.round(c.y), c.owner == null ? 0 : 1]);
    msg.grabLeft = g.cphase === 'grab' ? Math.max(0, g.grabEndAt - now) : 0;
    // 음악이 언제 끝나는지는 절대 보내지 않는다 — 깜짝 정지가 이 게임의 전부
  }
  if (type === 'sadari') {
    msg.sPhase = g.sPhase; msg.round = g.round; msg.totalRounds = SADARI_ROUNDS;
    msg.lanes = SADARI_LANES; msg.prizes = g.prizes;
    msg.pickLeft = g.sPhase === 'pick' ? Math.max(0, g.pickEndAt - now) : 0;
    // 선택 중엔 칸별 인원수만 (눈치싸움). 가로줄·경로는 공개 순간에만 — 미리 보내면 추적해서 치팅 가능
    const counts = new Array(SADARI_LANES).fill(0);
    for (const p of room.players.values()) if (p.alive && p.pick >= 0) counts[p.pick]++;
    msg.counts = counts;
    if (g.sPhase === 'reveal') {
      msg.rungs = g.rungs; msg.map = g.map; msg.revealAt = g.revealAt;
      msg.picks = [...room.players.values()].filter(p => !p.waiting && p.pick >= 0).map(p => [p.id, p.pick]);
    }
  }
  if (type === 'timing') {
    const parts = [...room.players.values()].filter(p => !p.waiting);
    msg.tPhase = g.tPhase; msg.round = g.tIdx; msg.totalRounds = g.tTargets.length;
    msg.target = g.tTargets[g.tIdx];
    msg.startAt = g.tPhase === 'run' ? g.startAt : 0;      // 클라가 serverNow()로 부드럽게 애니메이션
    msg.hideAt = g.tPhase === 'run' ? g.hideAt : 0;
    msg.tappedCount = parts.filter(p => p.tapAt > 0).length;
    msg.partCount = parts.length;
    msg.pickLeft = g.tPhase === 'ready' ? Math.max(0, g.readyEndAt - now) : 0;   // 시작 전 카운트다운만 공개
    if (g.tPhase === 'reveal' && g.results) msg.results = g.results;             // [id, 오차ms(±), 점수, 퍼펙트]
  }
  if (type === 'ox') {
    const [q, answer] = g.oxQs[g.oxIdx] || ['', 0];
    msg.oxPhase = g.oxPhase; msg.oxIdx = g.oxIdx; msg.oxTotal = g.oxQs.length;
    msg.q = g.oxPhase === 'idle' ? '' : q;
    msg.pickLeft = g.oxPhase === 'show' ? Math.max(0, g.oxEndAt - now) : 0;
    if (g.oxPhase === 'reveal') { msg.oxAnswer = answer; msg.revived = g.oxRevived ? 1 : 0; }
  }
  if (type === 'pirate') {
    msg.pPhase = g.pPhase; msg.round = g.round;
    msg.slots = PIRATE_SLOTS; msg.knives = g.knives;
    msg.pickLeft = g.pPhase === 'pick' ? Math.max(0, g.pickEndAt - now) : 0;
    msg.pickedCount = [...room.players.values()].filter(p => p.alive && p.picks.length >= g.knives).length;
    msg.aliveCount = [...room.players.values()].filter(p => p.alive).length;
    if (g.pPhase === 'reveal') {
      msg.triggers = [...g.triggers]; msg.victims = g.victims; msg.revealAt = g.revealAt;
      msg.picks = [...room.players.values()].filter(p => !p.waiting && p.picks.length).map(p => [p.id, p.picks]);
    }
  }
  broadcast(room, msg);
}

function backToLobby(room) {
  if (room.timer) { clearInterval(room.timer); room.timer = null; }
  room.state = 'lobby'; room.game = null; room.gameType = null;
  // 게임 중 끊긴 채 안 돌아온 학생은 로비로 오면서 정리 (유령 누적·정원 조기 소진 방지)
  for (const p of [...room.players.values()]) {
    if (!p.connected) room.players.delete(p.id);
    else { p.alive = false; p.waiting = false; }
  }
  broadcast(room, { type: 'phase', state: 'lobby', st: Date.now() });
  sendRoster(room);
}

// ---------- WebSocket ----------
// maxPayload: 한 메시지 16KB 제한 (기본값 100MB라 대용량 도배에 무방비.
// 4KB였으나 퀴즈쇼 커스텀 문제 20개가 한글 UTF-8로 4KB를 넘을 수 있어 상향 — rate limit이 도배는 막는다)
const wss = new WebSocketServer({ server, maxPayload: 16384 });
wss.on('error', (e) => console.error('[wss 오류]', e.message));
server.on('error', (e) => console.error('[http 오류]', e.message));
// 서버가 죽으면 수업 중인 모든 방이 날아간다. 예상 못 한 예외는 로그만 남기고 계속 산다.
process.on('uncaughtException', (e) => console.error('[치명적 예외 - 계속 실행]', e && e.stack || e));
process.on('unhandledRejection', (e) => console.error('[처리 안 된 거부]', e));

const MSG_LIMIT = 60;        // 소켓당 초당 허용 메시지 수
const MSG_WINDOW_MS = 1000;

wss.on('connection', (ws) => {
  ws.roomCode = null; ws.playerId = null; ws.isHost = false;
  ws.isAlive = true; ws.msgCount = 0; ws.msgWindowAt = Date.now(); ws.roomsMade = 0;
  // 소켓 오류에 리스너가 없으면 그대로 프로세스가 죽는다 (모바일 접속이 끊길 때 흔함)
  ws.on('error', () => {});
  ws.on('pong', () => { ws.isAlive = true; });

  ws.on('message', (raw) => {
   try {
    // 초당 메시지 상한 — 한 명이 서버를 마비시키지 못하게
    const now0 = Date.now();
    if (now0 - ws.msgWindowAt > MSG_WINDOW_MS) { ws.msgWindowAt = now0; ws.msgCount = 0; }
    if (++ws.msgCount > MSG_LIMIT) return;

    let msg;
    try { msg = JSON.parse(raw); } catch { return; }
    if (!msg || typeof msg !== 'object') return;
    const room = ws.roomCode ? rooms.get(ws.roomCode) : null;
    if (room) room.lastActive = Date.now();

    switch (msg.type) {
      case 'ping':
        roomSend(ws, { type: 'pong', ct: msg.ct, st: Date.now() });
        break;

      case 'create_room': {
        // 한 소켓이 방을 계속 찍어내면 4자리 코드(9000개)가 고갈된다
        if (++ws.roomsMade > 3 || rooms.size >= 500) {
          roomSend(ws, { type: 'error', msg: '방을 더 만들 수 없습니다. 잠시 후 다시 시도하세요.' });
          return;
        }
        detachFromRoom(ws);   // 다른 방의 참가자였다면 그 자리를 비운다 (유령 방지)
        const r = createRoom();
        if (!r) { roomSend(ws, { type: 'error', msg: '방을 만들 수 없습니다. 잠시 후 다시 시도하세요.' }); return; }
        r.hostWs = ws; ws.roomCode = r.code; ws.isHost = true;
        roomSend(ws, { type: 'room_created', code: r.code, hostToken: r.hostToken });
        sendRoster(r);
        break;
      }

      case 'rejoin_host': {
        const r = rooms.get(String(msg.code));
        if (!r || r.hostToken !== msg.hostToken) { roomSend(ws, { type: 'host_rejoin_fail' }); return; }
        detachFromRoom(ws);   // 이전 참가 자리 정리
        r.hostWs = ws; ws.roomCode = r.code; ws.isHost = true;
        roomSend(ws, { type: 'room_created', code: r.code, hostToken: r.hostToken });
        sendRoster(r);
        sendCurrentPhase(r, ws); // 게임 중이었다면 TV를 게임 화면으로 되돌린다
        break;
      }

      case 'join': {
        const r = rooms.get(String(msg.code));
        if (!r) { roomSend(ws, { type: 'error', msg: '방이 없습니다. 코드를 확인하세요.' }); return; }
        // 학생으로 들어오는 순간 호스트 권한은 사라진다 (자기 방을 만든 뒤 남의 방을 조종하는 것 차단)
        if (ws.isHost) {
          const own = ws.roomCode ? rooms.get(ws.roomCode) : null;
          if (own && own.hostWs === ws) own.hostWs = null;
          ws.isHost = false;
        }
        // 이미 이 방에 들어와 있는 소켓이 join을 반복하면 유령 참가자가 쌓인다
        if (ws.playerId != null && ws.roomCode === r.code && r.players.has(ws.playerId)) return;
        // 다른 방의 참가자였다면 그 자리를 비운다 (콘솔로 방 갈아타며 유령 만드는 것 차단)
        if (ws.roomCode && ws.roomCode !== r.code) detachFromRoom(ws);

        if (msg.token) {
          const old = [...r.players.values()].find(p => p.token === msg.token);
          if (old) {
            old.ws = ws; old.connected = true; old.dropAt = 0;
            // 침팬지·같은 그림은 탈락 없는 점수형 — 유예(8초)를 넘겨 alive가 꺼진 학생도
            // 복귀하면 계속 참여시킨다 (퀴즈쇼·순간 포착과 동일한 규칙으로 통일)
            if ((r.gameType === 'chimp' || r.gameType === 'pairs')
                && r.state === 'playing' && !old.waiting && !old.alive) {
              old.alive = true; old.deadAt = 0;
            }
            ws.roomCode = r.code; ws.playerId = old.id;
            roomSend(ws, { type: 'join_ok', id: old.id, token: old.token, code: r.code, nick: old.nick, ci: old.ci, state: r.state, gameType: r.gameType });
            sendRoster(r);
            sendCurrentPhase(r, ws); // 남은 시간·화면을 진행 중인 판에 맞춘다
            return;
          }
        }

        if (r.players.size >= 40) { roomSend(ws, { type: 'error', msg: '방이 가득 찼습니다. (최대 40명)' }); return; }
        let nick = cleanNick(msg.nick);
        const names = new Set([...r.players.values()].map(p => p.nick));
        if (names.has(nick)) { let i = 2; while (names.has(nick + i)) i++; nick = nick + i; }

        const p = {
          id: r.nextId++, nick, token: token(), ws,
          ci: (r.nextId - 2) % 30,
          x: 0, y: 0, dirX: 0, dirY: 0,
          alive: false, deadAt: 0,
          infected: false, infectedAt: 0, patientZero: false,
          score: 0, wordDone: false,
          waiting: r.state !== 'lobby',
          connected: true,
        };
        r.players.set(p.id, p);
        ws.roomCode = r.code; ws.playerId = p.id;
        roomSend(ws, { type: 'join_ok', id: p.id, token: p.token, code: r.code, nick: p.nick, ci: p.ci, state: r.state, gameType: r.gameType });
        sendRoster(r);
        sendCurrentPhase(r, ws);
        break;
      }

      case 'input': {
        if (!room || ws.playerId == null) return;
        const p = room.players.get(ws.playerId);
        if (!p) return;
        let x = finite(msg.x), y = finite(msg.y);
        const len = Math.hypot(x, y);
        if (len > 1) { x /= len; y /= len; }
        p.dirX = finite(x); p.dirY = finite(y);
        break;
      }

      // 모기 잡기: 학생이 아레나를 탭한 좌표
      case 'swat': {
        if (!room || ws.playerId == null) return;
        const p = room.players.get(ws.playerId);
        if (!p || !room.game || !p.alive || p.waiting) return;
        const x = Math.max(0, Math.min(room.game.arenaW, finite(msg.x)));
        const y = Math.max(0, Math.min(room.game.arenaH, finite(msg.y)));
        mosSwat(room, p, x, y, Date.now());
        break;
      }

      // 인형 뽑기: 액션 버튼(집게 내리기)
      case 'action': {
        if (!room || ws.playerId == null) return;
        const p = room.players.get(ws.playerId);
        if (!p) return;
        if (room.gameType === 'claw') clawDrop(room, p);
        else if (room.gameType === 'gala' && room.state === 'playing' && p.alive) {
          const g2 = room.game, now2 = Date.now();
          if (now2 >= (p.fireReadyAt || 0) && g2.pb.filter(bl => bl.owner === p.id).length < GALA_MAX_SHOTS) {
            p.fireReadyAt = now2 + GALA_FIRE_CD;
            g2.pb.push({ x: p.x, y: p.y - GALA_SHIP_R - 4, owner: p.id });
          }
        }
        else if (room.gameType === 'race' && room.state === 'playing'
                 && p.alive && !p.finishedAt && (p.boostsLeft || 0) > 0
                 && Date.now() >= (p.boostUntil || 0)) {
          p.boostsLeft--;
          p.boostUntil = Date.now() + RACE_BOOST_MS;
        }
        else if (room.gameType === 'sumo' && room.state === 'playing' && p.alive) {
          const now2 = Date.now();
          if (now2 >= (p.dashReadyAt || 0)) {
            // 대시 방향: 조이스틱 → 현재 속도 → 위쪽 순으로 결정
            let dx = p.dirX, dy = p.dirY, len = Math.hypot(dx, dy);
            if (len < 0.2) {
              dx = p.vx || 0; dy = p.vy || 0; len = Math.hypot(dx, dy);
              if (len < 5) { dx = 0; dy = -1; len = 1; }
            }
            dx /= len; dy /= len;
            p.dashDx = finite(dx); p.dashDy = finite(dy);
            p.dashUntil = now2 + SUMO_DASH_MS;
            p.dashReadyAt = now2 + SUMO_DASH_CD;
          }
        }
        else if (room.gameType === 'run' && room.state === 'playing' && p.alive) {
          const now2 = Date.now();
          // 착지 후에만 다시 점프 (공중 이단 점프 없음)
          if (!p.jumpStartAt || now2 - p.jumpStartAt >= RUN_JUMP_MS) p.jumpStartAt = now2;
        }
        break;
      }

      // 10초를 잡아라: 탭! (한 번 누르면 확정, 서버 도착 시각으로 판정)
      case 'stop': {
        if (!room || ws.playerId == null || room.state !== 'playing' || room.gameType !== 'timing') return;
        const p = room.players.get(ws.playerId);
        const g = room.game;
        if (!p || p.waiting || g.tPhase !== 'run' || p.tapAt > 0) return;
        p.tapAt = Date.now();
        break;
      }

      // 퀴즈쇼·순간 포착: 4지선다 답 제출 (한 번 누르면 확정 — 카훗과 동일)
      case 'answer': {
        if (!room || ws.playerId == null || room.state !== 'playing') return;
        if (room.gameType !== 'quiz' && room.gameType !== 'flash') return;
        const p = room.players.get(ws.playerId);
        const g = room.game;
        const ph = room.gameType === 'quiz' ? g.qPhase : g.fPhase;
        if (!p || p.waiting || ph !== 'show' || p.qAnswer >= 0) return;
        const v = Math.floor(finite(msg.v));
        if (v >= 0 && v < 4) { p.qAnswer = v; p.qAnswerAt = Date.now(); }
        break;
      }

      // 사이먼: 4색 패드 입력 — 시퀀스는 서버에만 있어 서버가 대조한다
      // 블록 배틀: 버튼 입력 4종 — 판정은 전부 서버에서
      case 'tmove': {   // v: -1(왼쪽) / 1(오른쪽)
        if (!room || ws.playerId == null || room.state !== 'playing' || room.gameType !== 'tetris') return;
        const p = room.players.get(ws.playerId);
        if (!p || !p.alive || p.waiting || p.tPiece < 0) return;
        const dx = finite(msg.v) < 0 ? -1 : 1;
        if (tetFits(p, p.tX + dx, p.tY, p.tRot)) {
          p.tX += dx;
          if (p.tLockAt) p.tLockAt = Date.now() + TET_LOCK_MS;   // 이동하면 고정 유예 리셋(한 번의 조작 기회)
        }
        break;
      }
      case 'trot': {
        if (!room || ws.playerId == null || room.state !== 'playing' || room.gameType !== 'tetris') return;
        const p = room.players.get(ws.playerId);
        if (!p || !p.alive || p.waiting || p.tPiece < 0) return;
        const nr = (p.tRot + 1) % 4;
        for (const k of TET_KICKS) {
          if (tetFits(p, p.tX + k, p.tY, nr)) {
            p.tX += k; p.tRot = nr;
            if (p.tLockAt) p.tLockAt = Date.now() + TET_LOCK_MS;
            break;
          }
        }
        break;
      }
      case 'tsoft': {   // v: 1(누름) / 0(뗌) — 소프트드롭 토글
        if (!room || ws.playerId == null || room.state !== 'playing' || room.gameType !== 'tetris') return;
        const p = room.players.get(ws.playerId);
        if (!p || !p.alive || p.waiting) return;
        const on = !!finite(msg.v);
        if (on && !p.tSoft) p.tNextFallAt = Math.min(p.tNextFallAt, Date.now() + TET_SOFT_GRAV);
        p.tSoft = on;
        break;
      }
      case 'tdrop': {   // 하드드롭 — 즉시 바닥까지 + 고정
        if (!room || ws.playerId == null || room.state !== 'playing' || room.gameType !== 'tetris') return;
        const p = room.players.get(ws.playerId);
        if (!p || !p.alive || p.waiting || p.tPiece < 0) return;
        let dy = 0;
        while (tetFits(p, p.tX, p.tY + dy + 1, p.tRot)) dy++;
        p.tY += dy;
        p.score += dy * 2;                       // 하드드롭 보너스
        tetLock(room, p, Date.now());
        break;
      }

      // 그림 퀴즈: 지목(방장)·답 정하기(출제자)·그리기(출제자)·정답 제출(나머지)
      case 'dpick': {
        if (!room || room.state !== 'playing' || room.gameType !== 'draw') return;
        if (!isRoomHost(room, ws)) return;
        const g = room.game;
        if (g.dPhase !== 'pick') return;
        const t = room.players.get(Math.floor(finite(msg.id)));
        if (!t || t.waiting || !t.connected) return;
        g.drawer = t.id; g.dPhase = 'write'; g.writeEndAt = Date.now() + DRAW_WRITE_MS;
        g.answer = ''; g.strokes = []; g.round++; g.correctOrder = [];
        g.drawnIds.add(t.id);
        for (const p of room.players.values()) p.dGuessed = false;
        break;
      }
      case 'dword': {
        if (!room || ws.playerId == null || room.state !== 'playing' || room.gameType !== 'draw') return;
        const g = room.game;
        const p = room.players.get(ws.playerId);
        if (!p || p.id !== g.drawer || g.dPhase !== 'write') return;
        const norm = normalizeWord(msg.text);
        if (!norm || norm.length < 2 || norm.length > 12 || !/^[가-힣a-zA-Z0-9]+$/.test(norm)) {
          roomSend(ws, { type: 'dword_bad', reason: 'form' }); return;
        }
        if (hasBadWord(norm)) { roomSend(ws, { type: 'dword_bad', reason: 'bad' }); return; }
        g.answer = norm; g.dPhase = 'draw'; g.drawEndAt = Date.now() + DRAW_ROUND_MS;
        roomSend(ws, { type: 'dword_ok' });
        break;
      }
      case 'dstroke': {   // begin:1이면 새 선 시작, pts:[x,y,x,y…] (0~1000 정규화 좌표)
        if (!room || ws.playerId == null || room.state !== 'playing' || room.gameType !== 'draw') return;
        const g = room.game;
        const p = room.players.get(ws.playerId);
        if (!p || p.id !== g.drawer || g.dPhase !== 'draw') return;
        if (!Array.isArray(msg.pts) || msg.pts.length > 128 || msg.pts.length % 2) return;
        const pts = msg.pts.map(v => Math.max(0, Math.min(1000, Math.round(finite(v)))));
        const c = Math.max(0, Math.min(9, Math.floor(finite(msg.c))));
        const w = Math.max(0, Math.min(2, Math.floor(finite(msg.w))));
        if (msg.begin) {
          if (g.strokes.length >= DRAW_MAX_STROKES) return;
          g.strokes.push({ c, w, pts: [] });
        }
        const s = g.strokes[g.strokes.length - 1];
        if (!s || s.pts.length + pts.length > DRAW_MAX_PTS) return;
        s.pts.push(...pts);
        drawRelay(room, p.id, { type: 'dseg', begin: msg.begin ? 1 : 0, c: s.c, w: s.w, pts });
        break;
      }
      case 'dundo': case 'dclear': {
        if (!room || ws.playerId == null || room.state !== 'playing' || room.gameType !== 'draw') return;
        const g = room.game;
        const p = room.players.get(ws.playerId);
        if (!p || p.id !== g.drawer || g.dPhase !== 'draw') return;
        if (msg.type === 'dundo') g.strokes.pop(); else g.strokes.length = 0;
        drawRelay(room, p.id, { type: 'devt', v: msg.type === 'dundo' ? 'undo' : 'clear' });
        break;
      }
      case 'dguess': {
        if (!room || ws.playerId == null || room.state !== 'playing' || room.gameType !== 'draw') return;
        const g = room.game;
        const p = room.players.get(ws.playerId);
        if (!p || p.waiting || p.id === g.drawer || g.dPhase !== 'draw' || p.dGuessed) return;
        const norm = normalizeWord(msg.text);
        if (!norm || norm.length > 20) return;
        if (hasBadWord(norm)) { roomSend(ws, { type: 'dguess_bad' }); return; }
        if (norm === g.answer) {
          p.dGuessed = true;
          g.correctOrder.push(p.id);
          const idx = g.correctOrder.length - 1;
          const pts = WORD_POINTS[idx] != null ? WORD_POINTS[idx] : 1;
          p.score += pts;
          const drawer = room.players.get(g.drawer);
          if (drawer) drawer.score += 2;             // 출제자도 맞힌 사람 수만큼 점수 (잘 그릴 동기)
          broadcast(room, { type: 'dcorrect', id: p.id, order: idx + 1, points: pts });
        } else {
          // 오답은 TV 티커에 뜨는 재미 요소 — 금칙어는 위에서 걸렀고 길이도 제한
          broadcast(room, { type: 'dmiss', id: p.id, text: norm.slice(0, 12) });
        }
        break;
      }
      case 'dend': {   // 방장: 결과 발표
        if (!room || room.state !== 'playing' || room.gameType !== 'draw') return;
        if (!isRoomHost(room, ws)) return;
        if (room.game.dPhase !== 'pick') return;   // 라운드 진행 중엔 못 끝냄 (그리던 판 보호)
        endDraw(room);
        break;
      }

      case 'skey': {
        if (!room || ws.playerId == null || room.state !== 'playing' || room.gameType !== 'simon') return;
        const p = room.players.get(ws.playerId);
        const g = room.game;
        if (!p || !p.alive || p.waiting || g.siPhase !== 'input' || p.simonDone) return;
        const v = Math.floor(finite(msg.v));
        if (v < 0 || v > 3) return;
        if (v === g.seq[p.simonIdx]) {
          p.simonIdx++;
          if (p.simonIdx >= g.seq.length) p.simonDone = true;
        } else {
          p.alive = false; p.deadAt = Date.now(); p.outRound = g.siRound;   // 틀리면 즉시 탈락
        }
        break;
      }

      // 사다리·통아저씨: 칸 선택 (선택 시간 안에는 바꿀 수 있다)
      case 'pick': {
        if (!room || ws.playerId == null || room.state !== 'playing') return;
        const p = room.players.get(ws.playerId);
        if (!p || !p.alive || p.waiting) return;
        const g = room.game;
        const v = Math.floor(finite(msg.v));
        if (room.gameType === 'sadari' && g.sPhase === 'pick') {
          if (v >= 0 && v < SADARI_LANES) p.pick = v;
        } else if (room.gameType === 'pirate' && g.pPhase === 'pick') {
          if (v >= 0 && v < PIRATE_SLOTS) {
            const i = p.picks.indexOf(v);
            if (i >= 0) p.picks.splice(i, 1);                        // 같은 칸 다시 누르면 칼 뽑기(취소)
            else { if (p.picks.length >= g.knives) p.picks.shift(); p.picks.push(v); }  // 꽉 찼으면 오래된 칼 이동
          }
        } else if (room.gameType === 'chimp' && g.chPhase === 'input') {
          // 침팬지: 1부터 순서대로 탭 — 정답이면 +10, 라운드 완주 +15, 틀리면 이번 라운드 실패
          if (v >= 0 && v < g.cells.length && !p.chFail && p.chIdx < g.chN) {
            const expected = p.chIdx + 1;
            if (g.nums[v] === expected) {
              p.chIdx++; p.score += 10;
              if (p.chIdx >= g.chN) { p.chDoneAt = Date.now(); p.score += 15; }
            } else if (g.nums[v] > 0 && g.nums[v] <= p.chIdx) {
              // 이미 맞힌 칸 재탭 — 실수로 두 번 눌러도 봐준다
            } else {
              p.chFail = true;
            }
          }
        } else if (room.gameType === 'pairs') {
          // 같은 그림: 카드 뒤집기 — 앞면은 뒤집은 본인에게만 알려준다
          if (v >= 0 && v < PAIRS_TOTAL
              && !(p.pMask & (1 << v))                 // 이미 맞춘 칸은 무시
              && p.pFlipB < 0                          // 판정 대기 중엔 잠금
              && v !== p.pFlipA) {
            if (p.pFlipA < 0) p.pFlipA = v;
            else { p.pFlipB = v; p.pAttempts++; p.pResolveAt = Date.now() + 650; }
            roomSend(ws, { type: 'pairs_flip', i: v, face: g.faces[v] });
          }
        }
        break;
      }

      case 'word_submit': {
        if (!room || ws.playerId == null || room.state !== 'playing') return;
        const g = room.game;
        const p = room.players.get(ws.playerId);
        if (!p || !p.alive || p.wordDone || g.wordPhase !== 'show') return;

        if (room.gameType === 'word') {
          if (normalizeWord(msg.text) === normalizeWord(g.word)) {
            p.wordDone = true;
            g.correctOrder.push(p.id);
            const idx = g.correctOrder.length - 1;
            const pts = WORD_POINTS[idx] != null ? WORD_POINTS[idx] : 1;
            p.score += pts;
            roomSend(ws, { type: 'word_ok', order: idx + 1, points: pts });
          } else {
            roomSend(ws, { type: 'word_bad', reason: 'wrong' });
          }
        } else if (room.gameType === 'cho') {
          const norm = normalizeWord(msg.text);
          if (!norm) return;
          const free = CHO_FREE_CATS.has(g.category); // 자유 카테고리: 사전에 있는 단어면 무엇이든 정답
          if (hasBadWord(norm)) {
            roomSend(ws, { type: 'word_bad', reason: 'bad' });
          } else if (choseongOf(norm) !== g.pattern) {
            roomSend(ws, { type: 'word_bad', reason: 'cho' });
          } else if (!(g.answers && g.answers.has(norm))) {
            // 어느 카테고리든 사전(목록)에 있는 단어만 정답 — 초성만 맞는 아무 말 도배 방지
            roomSend(ws, { type: 'word_bad', reason: free ? 'dict' : 'list' });
          } else if (g.claimed.some(c => c.w === norm)) {
            roomSend(ws, { type: 'word_bad', reason: 'dup' });
          } else {
            p.wordDone = true;
            g.claimed.push({ w: norm, id: p.id });
            g.correctOrder.push(p.id);
            const idx = g.correctOrder.length - 1;
            const pts = WORD_POINTS[idx] != null ? WORD_POINTS[idx] : 1;
            p.score += pts;
            roomSend(ws, { type: 'word_ok', order: idx + 1, points: pts, word: norm });
          }
        }
        break;
      }

      case 'start_game':
        if (isRoomHost(room, ws) && (room.state === 'lobby' || room.state === 'result'))
          startGame(room, String(msg.game || 'bomb'), msg.opt);
        break;

      case 'back_to_lobby':
        if (isRoomHost(room, ws)) backToLobby(room);
        break;

      case 'close_room':
        if (isRoomHost(room, ws)) closeRoom(room, '선생님이 방을 닫았습니다.');
        break;

      case 'leave': {
        if (!room || ws.playerId == null) return;
        room.players.delete(ws.playerId);
        ws.playerId = null; ws.roomCode = null;
        sendRoster(room);
        break;
      }

      case 'kick': {
        if (!isRoomHost(room, ws)) return;
        const p = room.players.get(Number(msg.playerId));
        if (p) {
          roomSend(p.ws, { type: 'kicked' });
          try { p.ws.close(); } catch {}
          room.players.delete(p.id);
          sendRoster(room);
        }
        break;
      }
    }
   } catch (e) {
    // 메시지 하나 때문에 서버 전체가 죽지 않게 한다
    console.error('[메시지 처리 오류]', e && e.stack || e);
   }
  });

  ws.on('close', () => {
    const room = ws.roomCode ? rooms.get(ws.roomCode) : null;
    if (!room) return;
    if (ws.isHost && room.hostWs === ws) { room.hostWs = null; return; }
    if (ws.playerId != null) {
      const p = room.players.get(ws.playerId);
      if (p && p.ws === ws) {
        p.connected = false; p.dirX = 0; p.dirY = 0;
        if (room.state === 'lobby') {
          room.players.delete(p.id);
        } else if (p.alive) {
          // 바로 탈락시키지 않는다 — 폰이 잠기거나 새로고침한 학생은 돌아올 시간을 준다.
          // 유예 시간이 지나도 안 오면 tick()에서 이번 판에서 뺀다.
          p.dropAt = Date.now();
        }
        sendRoster(room);
      }
    }
  });
});

